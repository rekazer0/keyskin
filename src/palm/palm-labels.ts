export function palmBoardLabel(type: string): string {
  return BOARD_LABELS[type] ?? type
}

export function palmPartLabel(part: string): string {
  return PART_LABELS[part] ?? FIELD_LABELS[part] ?? part
}

export function palmFieldLabel(key: string): string {
  return FIELD_LABELS[key] ?? PART_LABELS[key] ?? key
}

export function palmStyleReference(key: string): "BACK_STYLE" | "FORE_STYLE" | "CELL_STYLE" | "SOUND_STYLE" | undefined {
  return STYLE_REFERENCES[key]
}
