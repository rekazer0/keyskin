import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { strFromU8, strToU8, unzipSync, zipSync } from 'fflate'
import { ssfFixture } from '../tests/helpers/ssf-fixture.mjs'
import { encodePng } from '../src/ssf/ssf-png.ts'

const path = '1080/status1/phoneSkin.ini'
const section = 'SMA_Key26Bg_Q'
const files = unzipSync(ssfFixture())
// A patterned image exposes stretching that solid-colour fixtures cannot show.
const data = new Uint8Array(98 * 142 * 4)
for (let y = 0; y < 142; y++) for (let x = 0; x < 98; x++) data.set([x * 2, y, (x + y) % 256, 255], (y * 98 + x) * 4)
files['1080/status1/26keyq.png'] = encodePng({ width: 98, height: 142, data })
files[path] = strToU8(strFromU8(files[path]).replace(`[${section}]\n`, `[${section}]\nDISABLED=26keyq.png,2,96,3,139\nNORMAL_ON=26fn.png,1,97,1,141\nPRESSED_ON=26keyq_press.png,2,96,3,139\n`))
for (const name of Object.keys(files)) if (name.startsWith('1080/status1/')) files[name.replace('1080/', '720/')] = files[name]
const server = await createServer({ root: new URL('..', import.meta.url).pathname, logLevel: 'error', server: { host: '127.0.0.1', port: 41967, strictPort: false, hmr: false } })
await server.listen()
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const editor = page.getByRole('dialog', { name: '编辑图片', exact: true })
const numbers = editor.locator('input[type=number]')
const sliders = editor.locator('input[type=range]')
const guides = editor.locator('.ui-image-editor-guide')
const state = () => page.evaluate(async ({ path, section }) => {
  const { appState } = await import('/src/app/state.ts')
  const { ssfDocument } = await import('/src/app/ssf-documents.ts')
  return { text: appState.archive.getText(path), undo: appState.undoStack.length,
    values: Object.fromEntries(['NORMAL', 'PRESSED', 'DISABLED', 'NORMAL_ON', 'PRESSED_ON'].map(key => [key, ssfDocument(path).get(section, key)])),
    twin: ssfDocument(path.replace('1080/', '720/')).get(section, 'NORMAL') }
}, { path, section })
const selectKeys = (actions, board = 'py_26') => page.evaluate(async ({ actions, board }) => {
  const { selectFile } = await import('/src/app/navigation.ts')
  const { appState } = await import('/src/app/state.ts')
  const { preview } = await import('/src/app/canvas-interaction.ts')
  selectFile(`light/skin/port/${board}.ini`)
  await preview.whenDrawn()
  appState.selectedKeySections = actions.map(action => preview.keys.find(key => key.center === action).section)
  ;(await import('/src/app/key-inspector.ts')).populateKeyInspector()
}, { actions, board })
const open = async (pressed = false, keyboard = false) => {
  const card = page.locator('#document-fields [data-inspector-group-label="背景"] .ui-style-state').nth(pressed ? 1 : 0)
  if (keyboard) { await card.focus(); await page.keyboard.press('Enter') }
  else await card.click()
  await editor.waitFor()
  await page.waitForFunction(() => document.querySelector('.ui-image-editor input[type=range]')?.disabled === false)
}
const finish = async () => { await editor.getByRole('button', { name: '完成', exact: true }).click(); await editor.waitFor({ state: 'hidden' }) }
const undo = () => page.evaluate(async () => (await import('/src/app/edit-history.ts')).undo())
const frame = () => page.evaluate(async () => {
  const { preview } = await import('/src/app/canvas-interaction.ts')
  await preview.sceneForState()
  await preview.whenDrawn()
  return {
    keyboard: preview.canvas.toDataURL(),
    sample: document.querySelector('.ui-image-editor-result canvas')?.toDataURL(),
  }
})
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  await page.locator('#browser-open').setInputFiles({ name: 'image-editor.ssf', mimeType: 'application/octet-stream', buffer: Buffer.from(zipSync(files)) })
  await page.waitForFunction(() => !document.querySelector('#open').disabled)
  const close = page.locator('#file-operation-dialog[open] #file-operation-close')
  if (await close.isVisible()) await close.click()
  await page.getByRole('button', { name: '编辑模式', exact: true }).click()
  await selectKeys(['q'])
  const before = await state()
  assert.equal(await page.locator('#document-fields [data-document-key=STRETCH]').count(), 0, 'stretch controls live only in the image editor')
  await open(false, true)
  assert.deepEqual(await state(), before, 'opening with Enter writes nothing')
  assert.deepEqual(await numbers.evaluateAll(inputs => inputs.map(input => input.value)), ['2', '96', '3', '139'])
  const originalFrame = await frame()
  const editorBox = await editor.boundingBox()
  const stageBox = await editor.locator('.ui-image-editor-preview').boundingBox()
  assert.ok(editorBox.width > 1000 && stageBox.width > editorBox.width * 0.6 && stageBox.height > editorBox.height * 0.6, 'the larger dialog gives most space to the canvas')
  const line = await guides.first().boundingBox()
  await guides.first().focus()
  assert.equal(await guides.first().evaluate((guide) => getComputedStyle(guide).outlineStyle), 'none', 'focused guides do not show the browser button outline')
  await page.mouse.move(line.x + line.width / 2, line.y + line.height / 2)
  await page.mouse.down()
  await page.mouse.move(line.x + line.width / 2 + 48, line.y + line.height / 2, { steps: 5 })
  assert.deepEqual(await state(), before, 'moving a guide previews without committing')
  const draggedFrame = await frame()
  assert.notEqual(draggedFrame.keyboard, originalFrame.keyboard, 'guide dragging redraws the keyboard before release')
  assert.notEqual(draggedFrame.sample, originalFrame.sample, 'guide dragging shows the actual stretched pixels')
  assert.ok(Number(await numbers.first().inputValue()) > 2)
  assert.equal(await sliders.first().inputValue(), await numbers.first().inputValue(), 'guide dragging also moves the slider')
  await page.keyboard.press('Escape')
  await page.mouse.up()
  assert.equal(await editor.isVisible(), true, 'Esc cancels the drag without closing the editor')
  assert.equal(await numbers.first().inputValue(), '2')
  assert.deepEqual(await state(), before)
  assert.deepEqual(await frame(), originalFrame, 'Esc restores both previews')
  // Every edge moves in source pixels, clamps before the opposite edge, and commits exactly once.
  for (let index = 0; index < 4; index++) {
    const box = await guides.nth(index).boundingBox()
    const start = { x: box.x + box.width / 2, y: box.y + box.height / 2 }
    const original = await numbers.nth(index).inputValue()
    await page.mouse.move(start.x, start.y)
    await page.mouse.down()
    await page.mouse.move(start.x + (index < 2 ? (index % 2 ? -40 : 40) : 0), start.y + (index < 2 ? 0 : (index % 2 ? -40 : 40)), { steps: 4 })
    assert.notEqual(await numbers.nth(index).inputValue(), original, 'each guide follows its drag axis')
    assert.deepEqual(await state(), before)
    await page.mouse.up()
    assert.equal((await state()).undo, before.undo + 1)
    assert.equal((await state()).values.NORMAL.split(',')[index + 1], await numbers.nth(index).inputValue())
    await finish(); await undo(); await open()
    assert.deepEqual(await state(), before)
  }
  await guides.first().press('Shift+ArrowRight')
  assert.equal((await state()).values.NORMAL, '26keyq.png,12,96,3,139', 'keyboard adjusts the focused guide')
  await finish(); await undo(); await open()
  const originalGuide = await guides.first().getAttribute('style')
  const beforeSliderFrame = await frame()
  await sliders.first().evaluate(range => {
    for (const value of ['5', '10', '20']) { range.value = value; range.dispatchEvent(new Event('input', { bubbles: true })) }
  })
  assert.deepEqual(await state(), before, 'dragging only previews')
  assert.notEqual(await guides.first().getAttribute('style'), originalGuide, 'guides follow the slider')
  assert.equal(await numbers.first().inputValue(), '20')
  const sliderFrame = await frame()
  assert.notEqual(sliderFrame.keyboard, beforeSliderFrame.keyboard, 'slider input redraws the keyboard before change')
  assert.notEqual(sliderFrame.sample, beforeSliderFrame.sample, 'slider input redraws the stretched sample')
  await sliders.first().press('Escape')
  assert.deepEqual(await state(), before)
  assert.deepEqual(await frame(), beforeSliderFrame, 'Esc restores a slider preview without a history entry')
  await sliders.first().evaluate(range => { range.value = '20'; range.dispatchEvent(new Event('input', { bubbles: true })) })
  await sliders.first().dispatchEvent('change')
  const edited = await state()
  assert.equal(edited.undo, before.undo + 1, 'one slider drag is one undo step')
  assert.equal(edited.values.NORMAL, '26keyq.png,20,96,3,139')
  assert.equal(edited.values.DISABLED, edited.values.NORMAL, 'an identical linked state follows')
  assert.equal(edited.values.PRESSED, before.values.PRESSED, 'pressed stays independent')
  assert.equal(edited.values.NORMAL_ON, before.values.NORMAL_ON, 'custom extended state stays independent')
  assert.equal(edited.twin, before.twin, 'other resolutions retain their own pixel coordinates')
  assert.deepEqual(await frame(), sliderFrame, 'committing keeps exactly the previewed result')
  await numbers.nth(1).fill('999')
  assert.equal(await numbers.nth(1).inputValue(), '98', 'typing clamps to the current image width')
  await editor.screenshot({ path: '/tmp/keyskin-ssf-image-editor.png' })
  await finish()
  await undo(); await undo()
  assert.deepEqual(await state(), before)
  await open(true)
  await numbers.first().fill('12')
  assert.equal((await state()).values.PRESSED, '26keyq_press.png,12,96,3,139')
  assert.equal((await state()).values.PRESSED_ON, '26keyq_press.png,12,96,3,139')
  assert.equal((await state()).values.NORMAL, before.values.NORMAL)
  const beforePicker = await state()
  await editor.getByRole('button', { name: '更换图片…', exact: true }).click()
  await page.frameLocator('#picker-frame').locator('#style-library-grid .ui-image-card').first().waitFor()
  await page.frameLocator('#picker-frame').locator('body').press('Escape')
  await page.locator('#picker-dialog').waitFor({ state: 'hidden' })
  assert.equal(await editor.isVisible(), true, 'Esc closes only the image picker')
  assert.deepEqual(await state(), beforePicker, 'cancelling image selection leaves the image unchanged')
  await editor.getByRole('button', { name: '更换图片…', exact: true }).click()
  await page.frameLocator('#picker-frame').locator('#style-library-grid .ui-image-card').filter({ hasText: '26fn' }).first().click()
  await page.locator('#picker-dialog').waitFor({ state: 'hidden' })
  await editor.getByText('按下 · 26fn.png', { exact: true }).waitFor()
  assert.equal((await state()).values.PRESSED, '26fn.png,12,96,3,139')
  assert.equal(await sliders.count(), 4, 'returning from the picker keeps the editor usable')
  await finish()
  await undo(); await undo()
  assert.deepEqual(await state(), before)
  await selectKeys(['F36'])
  const inherited = await state()
  await open(true)
  await numbers.first().fill('8')
  const backspace = await page.evaluate(async path => (await import('/src/app/ssf-documents.ts')).ssfDocument(path).get('SMA_Key26Bg_Backspace_Qwerty', 'PRESSED'), path)
  assert.equal(backspace, '26fn.png,8,97,1,141', 'editing an inherited pressed image creates only that state')
  await finish(); await undo()
  assert.deepEqual(await state(), inherited)
  await selectKeys(['q', 'w'])
  await open()
  assert.equal(await numbers.first().getAttribute('placeholder'), '混合')
  const mixedFrame = await frame()
  const mixedState = await state()
  await sliders.first().evaluate(range => { range.value = '5'; range.dispatchEvent(new Event('input', { bubbles: true })) })
  await sliders.first().press('Escape')
  assert.equal(await numbers.first().inputValue(), '', 'cancelling restores mixed coordinates')
  assert.deepEqual(await state(), mixedState)
  assert.deepEqual(await frame(), mixedFrame, 'cancelling preserves every selected key’s own band')
  await numbers.first().fill('5')
  assert.equal((await state()).values.NORMAL, '26keyq.png,5,96,3,139', 'mixed editing preserves other coordinates')
  assert.equal(await page.evaluate(async path => (await import('/src/app/ssf-documents.ts')).ssfDocument(path).get('KeyBg_Default_Latin', 'NORMAL'), path), '26key.png,5,97,1,141')
  await finish(); await undo()
  await selectKeys(['q'])
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' })
  await page.locator('.mobile-workspace-tabs [data-mobile-pane=inspector]').focus()
  await page.keyboard.press('Enter')
  await open(false, true)
  const box = await editor.boundingBox()
  assert.ok(box.x >= 0 && box.width <= 390 && box.height <= 844, 'mobile dialog stays inside the viewport')
  assert.ok(await editor.getByRole('button', { name: '更换图片…', exact: true }).isVisible())
  const mobileStage = await editor.locator('.ui-image-editor-preview').boundingBox()
  await editor.screenshot({ path: '/tmp/keyskin-ssf-image-editor-mobile.png' })
  assert.ok(mobileStage.height > box.height / 2, `the canvas remains the main area on mobile: ${mobileStage.height} / ${box.height}`)
  const mobileFrame = await frame()
  await sliders.first().evaluate(range => { range.value = '20'; range.dispatchEvent(new Event('input', { bubbles: true })) })
  await editor.getByRole('button', { name: '完成', exact: true }).focus()
  await page.keyboard.press('Escape')
  await editor.waitFor({ state: 'hidden' })
  assert.deepEqual(await state(), before, 'browsing and closing changes nothing')
  assert.equal((await frame()).keyboard, mobileFrame.keyboard, 'closing discards an uncommitted preview')
  if (process.env.SSF_SKIN_PATH) {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
    await page.locator('#browser-open').setInputFiles(process.env.SSF_SKIN_PATH)
    await page.waitForFunction(() => !document.querySelector('#open').disabled)
    const close = page.locator('#file-operation-dialog[open] #file-operation-close')
    if (await close.isVisible()) await close.click()
    await selectKeys(['F36'], 'py_9')
    await open()
    const original = await frame()
    await numbers.nth(1).fill('82')
    await sliders.first().evaluate(range => { range.value = '81'; range.dispatchEvent(new Event('input', { bubbles: true })) })
    const stretched = await frame()
    assert.notEqual(stretched.sample, original.sample, 'real 183×160 artwork changes at the same 183×160 layout size')
    assert.notEqual(stretched.keyboard, original.keyboard, 'real backspace changes on the keyboard too')
    await editor.screenshot({ path: '/tmp/keyskin-real-stretch-editor.png' })
    await sliders.first().dispatchEvent('change')
    assert.deepEqual(await frame(), stretched, 'real artwork commits exactly what was previewed')
    await finish()
    const key = await page.evaluate(async () => {
      const { preview } = await import('/src/app/canvas-interaction.ts')
      const { appState } = await import('/src/app/state.ts')
      const scene = await preview.sceneForState()
      const key = scene.keys.find(key => appState.selectedKeySections.includes(key.section))
      const canvas = document.createElement('canvas')
      canvas.width = key.rect.width * 2
      canvas.height = key.rect.height * 2
      const context = canvas.getContext('2d')
      context.scale(2, 2)
      context.translate(-key.rect.x, -key.rect.y)
      const { drawSceneLayer } = await import('/src/native-scene.ts')
      key.layers(false).back.forEach(layer => drawSceneLayer(context, layer))
      return canvas.toDataURL().split(',')[1]
    })
    const { writeFileSync } = await import('node:fs')
    writeFileSync('/tmp/keyskin-real-stretch-key.png', Buffer.from(key, 'base64'))
  }
  assert.deepEqual(errors, [])
  console.log('SSF image editor: live stretched pixels and keyboard, cancellation, mixed bands, close cleanup, large canvas, four guides, keyboard, one-step undo, validation, state isolation, linked states, picker return, inherited state, resolution copies and mobile passed')
} finally {
  await browser.close()
  await server.close()
}
