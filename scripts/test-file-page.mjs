import assert from "node:assert/strict"
import { mkdirSync } from "node:fs"
import { chromium } from "playwright"
import { createServer } from "vite"

const server = await createServer({ logLevel: "error", server: { host: "127.0.0.1", port: 41908, strictPort: false, hmr: false } })
await server.listen()
const browser = await chromium.launch()
mkdirSync(".ui-current/file-page", { recursive: true })
try {
  for (const colorScheme of ["light", "dark"]) {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme })
    const errors = []
    page.on("pageerror", error => errors.push(error.message))
    await page.addInitScript(() => localStorage.setItem("onboarding-tour-v1", "done"))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
    const fileEntry = page.locator('[data-workspace-page="files"]')
    const form = page.locator("#file-project-chooser #new-project-form")
    await form.waitFor()
    for (const platform of [null, "macos", "windows"]) {
      if (platform) await page.evaluate(platform => document.documentElement.classList.add(platform), platform)
      assert.equal(await page.locator('.titlebar .document-title').isVisible(), false)
      assert.equal(await page.locator('#pinned-toolbar').isVisible(), false)
      const main = await page.locator('main').boundingBox()
      assert.equal(main.y, 0, "file page starts at the top of the window")
      assert.equal(main.height, 1000, "file page fills the height released by the titlebar")
      assert.equal(await page.locator('#window-close').isVisible(), platform === "windows", "Windows keeps its window controls")
      if (platform) await page.evaluate(platform => document.documentElement.classList.remove(platform), platform)
    }
    assert.equal(await page.locator('.titlebar .document-title').isVisible(), false)
    assert.equal(await page.locator('.home-settings').count(), 0)
    await page.locator('#workspace-navigation [data-settings-entry="settings"]').click()
    await page.locator('#settings-workspace:not([hidden])').waitFor()
    assert.equal(await page.locator(".welcome-hero h1").textContent(), "键盘皮肤工作台")
    await page.keyboard.press('Escape')
    await page.locator('#settings-workspace').waitFor({ state: 'hidden' })
    assert.equal(await fileEntry.getAttribute("aria-current"), "page")
    assert.equal(await form.locator(".project-template-card").count(), 8)
    assert.equal(await page.locator("#new-project-dialog").isVisible(), false)

    // 方向键只浏览，单击模板直接新建；名称与保存位置留到首次保存。
    assert.equal(await form.locator('[name="project-name"], [name="project-save-path"], .project-location').count(), 0)
    assert.equal(await page.locator(".canvas-wrap.empty:has(.welcome-main)").count(), 1)
    const selected = form.locator('.project-template-card[aria-selected="true"]')
    await selected.focus()
    await selected.press("Home")
    await selected.press("ArrowRight")
    assert.equal(await selected.getAttribute("data-template"), "official-android-bds")
    assert.equal(await page.locator(".canvas-wrap.empty:has(.welcome-main)").count(), 1, "arrow keys only browse templates")
    assert.equal(await form.locator("footer").count(), 0, "no bottom creation module")
    await selected.click()
    await page.locator(".canvas-wrap:not(.empty):has(.welcome-main)").waitFor()
    await page.waitForFunction(() => !document.querySelector("#open").disabled)
    assert.equal(await page.locator("#document-name").textContent(), "未命名.bds")
    assert.equal(await page.locator('.titlebar').isVisible(), true, "editor retains its titlebar")
    await page.evaluate(async () => { window.filePageArchive = (await import("/src/app/state.ts")).appState.archive })

    // 返回文件页再回概览，保留同一份未保存文档。
    await fileEntry.click()
    assert.equal(await form.isVisible(), true)
    assert.equal((await page.locator('main').boundingBox()).y, 0, "returning to files removes the titlebar again")
    await page.locator('[data-workspace-page="overview"]').click()
    assert.equal(await page.locator('.titlebar').isVisible(), true)
    assert.equal(await page.locator(".canvas-wrap:not(.empty):has(.welcome-main)").count(), 1)
    assert.equal(await page.evaluate(async () => window.filePageArchive === (await import("/src/app/state.ts")).appState.archive), true)
    await fileEntry.click()
    const defaultTemplate = form.locator('[data-template="default-android"]')
    await defaultTemplate.focus()
    await defaultTemplate.press("Home")
    await defaultTemplate.press("Enter")
    const confirmation = page.locator('dialog[data-variant="ask"][open]')
    await confirmation.waitFor()
    await confirmation.getByRole("button", { name: "取消", exact: true }).click()
    await confirmation.waitFor({ state: "hidden" })
    await page.waitForFunction(() => !document.querySelector("#open").disabled)
    assert.equal(await page.evaluate(async () => window.filePageArchive === (await import("/src/app/state.ts")).appState.archive), true)

    // 文件页的新建入口定位到同一表单，不弹出独立窗口。
    await page.evaluate(async () => (await import("/src/app/new-document.ts")).startNewDocument())
    assert.equal(await page.locator("#new-project-dialog").isVisible(), false)
    assert.equal(await form.isVisible(), true)
    assert.equal(page.context().pages().length, 1)
    await page.evaluate(async () => {
      const { recordRecentFile } = await import("/src/app/recent-files.ts")
      document.querySelector(".welcome-recent").removeAttribute("data-platform-hidden")
      recordRecentFile("/tmp/合并页测试.bds", "合并页测试.bds")
    })
    assert.equal(await page.locator("#welcome-recent-title").textContent(), "我的皮肤")
    assert.equal(await page.locator("#welcome-recent-grid .recent-card").count(), 1)
    assert.equal(await form.isVisible(), true, "recent files and creation share one page")
    await page.locator("#recent-clear").click()
    assert.equal(await page.locator("#welcome-recent-empty").isVisible(), true)
    for (const width of [1440, 1024, 800]) {
      await page.setViewportSize({ width, height: 1000 })
      const lastTemplate = form.locator(".project-template-card").last()
      await lastTemplate.scrollIntoViewIfNeeded()
      const action = await lastTemplate.boundingBox()
      assert.ok(action.y >= 0 && action.y + action.height <= 1000, "template stays reachable by scrolling the page")
      assert.equal(await page.evaluate(() => document.body.scrollWidth > innerWidth), false)
      const geometry = await form.evaluate(node => {
        const rect = node.getBoundingClientRect()
        return { width: rect.width, scroll: node.scrollWidth }
      })
      assert.ok(geometry.scroll <= geometry.width + 1, JSON.stringify(geometry))
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.locator(".welcome-main").evaluate(node => { node.scrollTop = 0 })
    await page.screenshot({ path: `.ui-current/file-page/${colorScheme}.png` })
    // 我的皮肤随页面宽度增减列数，桌面最多排满三行。
    await page.evaluate(async () => {
      const { recordRecentFile } = await import("/src/app/recent-files.ts")
      for (let index = 0; index < 20; index++) recordRecentFile(`/tmp/皮肤-${index}.bds`, `皮肤-${index}.bds`)
    })
    for (const [width, columns] of [[1920, 7], [1440, 5], [1024, 3], [800, 2]]) {
      await page.setViewportSize({ width, height: 720 })
      await page.locator(".welcome-main").evaluate(node => { node.scrollTop = 0 })
      const expectedCards = Math.min(20, columns * 3)
      await page.waitForFunction(expected => document.querySelector("#welcome-recent-grid").childElementCount === expected, expectedCards)
      const recent = await page.locator("#welcome-recent-grid").boundingBox()
      const card = page.locator("#welcome-recent-grid .recent-card").first()
      const geometry = await card.evaluate(node => {
        const preview = node.querySelector(".template-preview").getBoundingClientRect()
        const info = node.querySelector(".template-foot").getBoundingClientRect()
        return { direction: getComputedStyle(node).flexDirection, width: node.getBoundingClientRect().width, previewHeight: preview.height, previewBottom: preview.bottom, infoTop: info.top, nameSize: getComputedStyle(node.querySelector('.template-name')).fontSize, metaSize: getComputedStyle(node.querySelector('.template-meta')).fontSize }
      })
      assert.equal(geometry.direction, "column", "recent files use vertical preview cards")
      assert.equal(await card.evaluate(node => getComputedStyle(node).borderTopWidth), "1px", "recent cards retain their thin outline")
      const template = await form.locator('.project-template-card').first().boundingBox()
      assert.ok(geometry.width >= 220, "cards keep their minimum readable width")
      assert.ok(Math.abs(geometry.width - template.width) < 1, "recent files and templates share column widths")
      const templateColumns = await form.locator('.project-template-grid').evaluate(node => getComputedStyle(node).gridTemplateColumns.split(' ').length)
      assert.equal(templateColumns, columns, `${width}px uses ${columns} template columns`)
      assert.ok(Math.abs(geometry.width * columns + 16 * (columns - 1) - recent.width) < 1, "columns fill the available page width")
      assert.equal(geometry.previewHeight, 160)
      assert.equal(geometry.nameSize, '12px')
      assert.equal(geometry.metaSize, '11px')
      assert.ok(geometry.infoTop >= geometry.previewBottom, "file information follows the large preview")
      const rows = await page.locator("#welcome-recent-grid .recent-card").evaluateAll(nodes => new Set(nodes.map(node => node.offsetTop)).size)
      assert.equal(rows, Math.ceil(expectedCards / columns), "recent cards fill at most three rows")
      assert.equal(await page.locator("#welcome-recent-hint").textContent(), "20 条")
      const lastRecent = page.locator("#welcome-recent-grid .recent-card").last()
      await lastRecent.scrollIntoViewIfNeeded()
      const lastRecentBox = await lastRecent.boundingBox()
      assert.ok(lastRecentBox.y >= 0 && lastRecentBox.y + lastRecentBox.height <= 720, "last recent card can be fully scrolled into view")
      await form.locator('.project-template-card').last().scrollIntoViewIfNeeded()
      const last = await form.locator('.project-template-card').last().boundingBox()
      assert.ok(last.y >= 0 && last.y + last.height <= 720, "last template can be fully scrolled into view")
      assert.equal(await page.evaluate(() => document.body.scrollWidth > innerWidth), false)
      if (width >= 1440) {
        await page.locator(".welcome-main").evaluate(node => { node.scrollTop = 0 })
        await page.screenshot({ path: `.ui-current/file-page/${colorScheme}-${width}.png` })
      }
    }
    await page.setViewportSize({ width: 1024, height: 720 })
    await page.locator(".welcome-main").evaluate(node => { node.scrollTop = 0 })
    await page.screenshot({ path: `.ui-current/file-page/${colorScheme}-recent.png` })
    const cards = page.locator('#welcome-recent-grid [role="option"]')
    const previous = page.locator("#recent-prev")
    const next = page.locator("#recent-next")
    const pageNumber = page.locator("#recent-page-number")
    const savedPaths = () => page.evaluate(() => JSON.parse(localStorage.getItem("recent-files") ?? "[]").map(item => item.path))
    assert.equal((await savedPaths()).length, 20, "page size is independent of history retention")
    assert.equal(await pageNumber.textContent(), "1 / 3")
    assert.equal(await previous.isDisabled(), true)
    await next.focus()
    await next.press("Enter")
    assert.equal(await pageNumber.textContent(), "2 / 3")
    assert.equal(await cards.count(), 9)
    assert.equal(await cards.first().getAttribute("data-recent"), "/tmp/皮肤-10.bds")
    await next.click()
    assert.equal(await pageNumber.textContent(), "3 / 3")
    assert.equal(await cards.count(), 2)
    assert.equal(await cards.last().getAttribute("data-recent"), "/tmp/皮肤-0.bds")
    assert.equal(await next.isDisabled(), true)
    await previous.click()
    assert.equal(await cards.count(), 9)
    await next.click()
    await page.screenshot({ path: `.ui-current/file-page/${colorScheme}-recent-last.png`, animations: "disabled" })
    await page.setViewportSize({ width: 1440, height: 720 })
    await page.waitForFunction(() => document.querySelector("#recent-page-number").textContent === "2 / 2")
    assert.equal(await cards.count(), 5, "wider windows repaginate when viewing the last page")
    assert.equal(await cards.last().getAttribute("data-recent"), "/tmp/皮肤-0.bds")
    await page.evaluate(async () => {
      const { recordRecentFile } = await import("/src/app/recent-files.ts")
      for (let index = 20; index < 30; index++) recordRecentFile(`/tmp/皮肤-${index}.bds`, `皮肤-${index}.bds`)
    })
    assert.deepEqual(await savedPaths(), Array.from({ length: 27 }, (_, index) => `/tmp/皮肤-${29 - index}.bds`))

    const openFileSettings = async () => {
      await page.locator('#workspace-navigation [data-settings-entry="settings"]').click()
      await page.locator("#settings-tab-files").click()
    }
    const limit = page.locator("#recent-history-limit")
    await openFileSettings()
    assert.equal(await limit.inputValue(), "27", "defaults to keeping the last 27 skins")
    await limit.fill("5")
    await page.locator("#settings-cancel").click()
    await page.locator("#settings-workspace").waitFor({ state: "hidden" })
    assert.equal((await savedPaths()).length, 27, "cancel must not trim history")
    await openFileSettings()
    assert.equal(await limit.inputValue(), "27")
    await limit.fill("-1")
    await page.locator("#settings-save").click()
    assert.equal(await page.locator("#settings-workspace").isVisible(), true, "negative limits are invalid")
    await limit.fill("5")
    await page.screenshot({ path: `.ui-current/file-page/${colorScheme}-recent-settings.png` })
    await page.locator("#settings-save").click()
    await page.locator("#settings-workspace").waitFor({ state: "hidden" })
    assert.deepEqual(await savedPaths(), [29, 28, 27, 26, 25].map(index => `/tmp/皮肤-${index}.bds`))
    assert.equal(await cards.count(), 5, "page clamps after trimming history")
    assert.equal(await page.locator("#recent-pagination").isVisible(), false)
    await page.evaluate(async () => {
      const { recordRecentFile } = await import("/src/app/recent-files.ts")
      recordRecentFile("/tmp/皮肤-30.bds", "皮肤-30.bds")
      recordRecentFile("/tmp/皮肤-28.bds", "皮肤-28.bds")
    })
    assert.deepEqual(await savedPaths(), [28, 30, 29, 27, 26].map(index => `/tmp/皮肤-${index}.bds`))
    await openFileSettings()
    assert.equal(await limit.inputValue(), "5")
    await limit.fill("0")
    await page.locator("#settings-save").click()
    await page.locator("#settings-workspace").waitFor({ state: "hidden" })
    await page.evaluate(async () => {
      const { recordRecentFile } = await import("/src/app/recent-files.ts")
      for (let index = 31; index < 36; index++) recordRecentFile(`/tmp/皮肤-${index}.bds`, `皮肤-${index}.bds`)
    })
    assert.equal((await savedPaths()).length, 10, "choosing unlimited lets history grow again")
    await page.setViewportSize({ width: 390, height: 844 })
    await page.waitForFunction(() => document.querySelector("#recent-page-number").textContent === "1 / 2")
    await next.click()
    assert.equal(await pageNumber.textContent(), "2 / 2")
    assert.equal(await cards.count(), 1)
    assert.equal(await page.evaluate(() => document.body.scrollWidth > innerWidth), false)
    await page.screenshot({ path: `.ui-current/file-page/${colorScheme}-recent-mobile.png`, animations: "disabled" })
    await page.locator('#mobile-navigation [data-settings-entry="settings"]').click()
    await page.locator(".mobile-settings-overview").getByRole("button", { name: "文件", exact: true }).click()
    assert.equal(await limit.isVisible(), true, "mobile settings links to the same retention input")
    assert.equal(await limit.inputValue(), "0")
    await page.locator("#settings-cancel").click()
    await page.locator("#settings-workspace").waitFor({ state: "hidden" })
    for (const viewport of [{ width: 390, height: 844 }, { width: 844, height: 390 }]) {
      await page.setViewportSize(viewport)
      await page.locator("#new-project-dialog #new-project-form").waitFor({ state: "attached" })
      assert.equal(await page.locator("#new-project-dialog #new-project-form").count(), 1)
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await form.waitFor()
    assert.equal(await form.count(), 1)
    assert.deepEqual(errors, [])
    await page.close()
    console.log(`file page ${colorScheme}: passed`)
  }
  for (const [viewport, activation] of [
    [{ width: 390, height: 844 }, "click"],
    [{ width: 844, height: 390 }, "Space"],
  ]) {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    await page.addInitScript(() => localStorage.setItem("onboarding-tour-v1", "done"))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
    await page.locator("#mobile-welcome-new").click()
    const dialog = page.locator("#new-project-dialog")
    assert.equal(await dialog.locator("footer").count(), 0)
    await page.keyboard.press("Escape")
    await dialog.waitFor({ state: "hidden" })
    assert.equal(await page.locator(".canvas-wrap.empty:has(.welcome-main)").count(), 1, "closing the chooser creates nothing")
    await page.locator("#mobile-welcome-new").click()
    await page.setViewportSize(viewport)
    const template = dialog.locator('[data-template="official-android-bds"]')
    if (activation === "click") await template.locator("strong").click()
    else { await template.focus(); await template.press(activation) }
    await dialog.waitFor({ state: "hidden" })
    await page.locator(".canvas-wrap:not(.empty):has(.welcome-main)").waitFor()
    await page.waitForFunction(() => !document.querySelector("#open").disabled)
    assert.equal(await page.locator("#document-name").textContent(), "未命名.bds")
    await page.close()
    console.log(`mobile template ${activation}: passed`)
  }
} finally {
  await browser.close()
  await server.close()
}
