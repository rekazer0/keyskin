import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
import { strFromU8, strToU8, unzipSync, zipSync } from 'fflate'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { mobilePenFixture } from '../tests/helpers/mobile-pen-fixture.mjs'

const root = new URL('..', import.meta.url).pathname
const out = `${root}.ui-current/mobile-style-layers`
mkdirSync(out, { recursive: true })
const path = 'light/skin/port/py_26.ini'
const files = unzipSync(mobilePenFixture())
files[path] = strToU8(strFromU8(files[path]).replace('FORE_STYLE=41\n', 'FORE_STYLE=41,100\n').replace('FORE_STYLE=42\n', 'FORE_STYLE=42,100\n'))
const server = await createServer({ root, logLevel: 'error', server: { host: '127.0.0.1', port: 0, hmr: false } })
await server.listen()
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 393, height: 852 }, hasTouch: true })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}`)
  await page.locator('.template-card').first().waitFor({ state: 'attached' })
  await page.locator('#browser-open').setInputFiles({ name: '分层.bds', mimeType: 'application/octet-stream', buffer: Buffer.from(zipSync(files)) })
  await page.waitForFunction(() => !document.querySelector('#save').disabled)
  await page.waitForFunction(() => !document.querySelector('#file-operation-dialog').open || !document.querySelector('#file-operation-close').disabled)
  const close = page.locator('#file-operation-dialog[open] #file-operation-close')
  if (await close.isVisible()) await close.click()
  await page.getByRole('button', { name: '开始编辑', exact: true }).click()
  await page.evaluate(async path => {
    const { appState } = await import('/src/app/state.ts')
    const { preview } = await import('/src/app/canvas-interaction.ts')
    ;(await import('/src/app/navigation.ts')).selectFile(path)
    appState.selectedKeySections = ['KEY11']
    preview.setSelected(['KEY11'])
    ;(await import('/src/app/key-inspector.ts')).populateKeyInspector()
    ;(await import('/src/app/mobile-layout.ts')).setMobilePane('inspector')
  }, path)
  const appearance = page.locator('.mobile-appearance')
  const layer = name => appearance.getByRole('button', { name, exact: true })
  const snapshot = () => page.evaluate(async () => {
    const { appState: s } = await import('/src/app/state.ts')
    return { undo: s.undoStack.length, fore: s.layoutDocument.get('KEY11', 'FORE_STYLE'), neighbor: s.layoutDocument.get('KEY12', 'FORE_STYLE'),
      back: s.layoutDocument.get('KEY11', 'BACK_STYLE'), styles: s.archive.getText('light/skin/res/default.css') }
  })
  const picker = page.frameLocator('#picker-frame')
  const undo = () => page.locator('#mobile-undo').click()
  const apply = async () => {
    await picker.locator('#style-library-apply').click()
    await page.locator('#picker-dialog').waitFor({ state: 'hidden' })
  }
  const before = await snapshot()
  assert.deepEqual(await appearance.locator('.mobile-appearance-layers button').allTextContents(), ['背景', '前景 1', '前景 2'])
  await page.locator('#mobile-property-tabs [data-mobile-category="appearance"]').click()
  assert.equal(await appearance.getByRole('group', { name: '样式图层' }).count(), 1)
  assert.doesNotMatch(await appearance.innerText(), /外观/)
  const backNumber = appearance.getByRole('textbox', { name: '背景样式编号' })
  await backNumber.fill('100'); await backNumber.press('Tab')
  assert.deepEqual(await snapshot(), { ...before, back: '100', undo: before.undo + 1 })
  await undo()
  await layer('移除背景引用').click()
  const removed = await snapshot()
  assert.equal(removed.back, '')
  await layer('选择样式').press('Enter')
  await picker.locator('#picker-close').click()
  await page.locator('#picker-dialog').waitFor({ state: 'hidden' })
  assert.deepEqual(await snapshot(), removed, '空样式入口可用键盘打开，取消不补写引用')
  await undo()
  assert.deepEqual(await snapshot(), before)
  await layer('前景 2').click()
  assert.equal(await page.locator('#mobile-inspector-groups [aria-pressed=true]').innerText(), '样式', 'switching layer stays in the style section')
  const number = appearance.getByRole('textbox', { name: '前景 2样式编号' })
  await number.fill('41')
  await number.press('Tab')
  assert.deepEqual(await snapshot(), { ...before, undo: before.undo + 1, fore: '41,41' })
  assert.match(await appearance.locator('.ui-scope-note').innerText(), /本键 2 层共用/)
  await layer('为选中按键创建独立前景 2样式').click()
  const duplicate = await snapshot()
  assert.match(duplicate.fore, /^41,\d+$/)
  assert.notEqual(duplicate.fore, '41,41')
  assert.equal(duplicate.neighbor, before.neighbor)
  assert.equal(duplicate.undo, before.undo + 2)
  await undo()
  await undo()
  assert.deepEqual(await snapshot(), before)
  await layer('前景 1').click()
  await layer('预览前景 1按下状态').click()
  assert.equal(await page.locator('#picker-dialog[open]').count(), 0, '文字状态不会修改图片')
  const images = await appearance.locator('canvas').evaluateAll(nodes => nodes.map(node => node.toDataURL()))
  assert.notEqual(...images, '文字层的正常和按下态分别绘制')
  await layer('前景 2').click()
  assert.match(await appearance.locator('[data-appearance-state="pressed"]').innerText(), /前景 2 · 按下/)
  await page.locator('#mobile-inspector-resize').press('Home')
  await appearance.scrollIntoViewIfNeeded()
  await appearance.screenshot({ path: `${out}/mobile.png`, animations: 'disabled' })
  await layer('更换前景 2按下图片').click()
  await picker.locator('[data-path$="key_tint.png"]').click()
  await page.waitForFunction(async () => {
    const draft = (await import('/src/app/canvas-interaction.ts')).preview.draftVisual
    return draft?.foreground && draft.layer === 1 && draft.pressed && draft.section === 'KEY11' && draft.visual?.image
  })
  await picker.locator('#style-library-cancel').click()
  await page.locator('#picker-dialog').waitFor({ state: 'hidden' })
  assert.deepEqual(await snapshot(), before, '取消不改引用、样式或历史')
  await layer('更换前景 2按下图片').click()
  await picker.locator('[data-path$="key_tint.png"]').click()
  await apply()
  const shared = await snapshot()
  assert.deepEqual(shared, { ...before, undo: before.undo + 1, styles: before.styles.replace('HL_IMG=key_matte,1', 'HL_IMG=key_tint,1') })
  await undo()
  assert.deepEqual(await snapshot(), before)
  await layer('为选中按键创建独立前景 2样式').click()
  const isolated = await snapshot()
  assert.match(isolated.fore, /^41,\d+$/)
  assert.notEqual(isolated.fore, before.fore)
  assert.equal(isolated.back, before.back)
  assert.equal(isolated.neighbor, before.neighbor)
  assert.equal(isolated.undo, before.undo + 1)
  await undo()
  assert.deepEqual(await snapshot(), before)
  const replace = appearance.locator('.mobile-appearance-reference').getByRole('button', { name: '更换样式', exact: true })
  await page.setViewportSize({ width: 320, height: 720 })
  const { width, height } = await replace.boundingBox()
  assert.ok(width >= 44 && height >= 44, '窄屏更换入口仍有足够的触控面积')
  await replace.tap()
  await picker.locator('[data-style-id="100"][aria-selected="true"]').waitFor()
  assert.deepEqual(await snapshot(), before, '打开时定位当前前景样式，不改引用')
  await picker.locator('#resource-search').fill('2')
  await picker.locator('#style-library-grid [data-style-id="2"]').click()
  await apply()
  assert.deepEqual(await snapshot(), { ...before, undo: before.undo + 1, fore: '41,2' })
  await page.setViewportSize({ width: 393, height: 852 })
  await undo()
  await layer('添加前景').click()
  await picker.locator('#resource-search').fill('2')
  await picker.locator('#style-library-grid [data-style-id="2"]').click()
  await apply()
  assert.equal((await snapshot()).fore, '41,100,2')
  await layer('前景 3').click()
  await layer('移除前景 3引用').click()
  assert.equal((await snapshot()).fore, before.fore)
  await undo(); await undo()
  assert.deepEqual(await snapshot(), before)
  await layer('前景 2').click()
  await layer('编辑前景 2样式资源').click()
  assert.deepEqual(await page.evaluate(async () => {
    const { appState } = await import('/src/app/state.ts')
    return [appState.selectedStyleID, appState.selectedPath, appState.styleReturnSelection]
  }), ['100', 'light/skin/res/default.css', ['KEY11']])
  await page.locator('#style-resource-detail').waitFor({ state: 'visible' })
  await page.locator('#resource-back').click()
  assert.deepEqual(await snapshot(), before)
  await page.setViewportSize({ width: 1440, height: 900 })
  await appearance.waitFor({ state: 'hidden' })
  const pc = page.locator('.key-appearance-fields')
  assert.deepEqual(await pc.locator('[title="FORE_STYLE"] .ui-style-ref-number').evaluateAll(nodes => nodes.map(node => node.value)), ['41', '100'])
  await pc.screenshot({ path: `${out}/pc.png`, animations: 'disabled' })
  assert.deepEqual(errors, [])
  console.log('通过：背景与两层前景、状态预览、共享图片替换、独立复制、选换／增删引用及撤销；已保存 PC 和手机截图。')
} finally {
  await browser.close()
  await server.close()
}
