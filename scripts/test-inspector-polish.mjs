import assert from "node:assert/strict"
import { chromium } from "playwright"
import { createServer } from "vite"

const server = await createServer({ logLevel: "error", server: { host: "127.0.0.1", port: 41942, strictPort: false } })
await server.listen()
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, bypassCSP: true })
const errors = []
page.on("pageerror", (error) => errors.push(error.message))
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  await page.locator('.template-card[data-template="xiaomi-unified-rounded-blur"]').click()
  await page.waitForFunction(() => !document.querySelector("#open").disabled)
  await page.waitForFunction(() => !document.querySelector("#file-operation-dialog").open)
  await page.getByRole("button", { name: "编辑模式", exact: true }).click()
  await page.evaluate(async () => {
    const { appState } = await import("/src/app/state.ts")
    await (await import("/src/app/navigation.ts")).selectFile(appState.layoutPath)
  })
  const group = page.locator(".text-style-fields")
  const styleText = () => page.evaluate(async () => {
    const { appState } = await import("/src/app/state.ts")
    const { styleConfigPath } = await import("/src/app/config-context.ts")
    return appState.archive.getText(styleConfigPath())
  })
  const note = group.locator("#text-style-note")
  assert.match(await note.textContent(), /\d+ 个样式/)
  assert.match(await note.getAttribute("title"), /修改本布局/)
  assert.equal(await note.locator("svg").count(), 1)
  assert.equal(await note.getAttribute("tabindex"), "0")
  // 皮肤字体是整个皮肤共用的内嵌字体；字体名称是这个文字样式自己的字体，两者的悬停说明写清生效平台。
  assert.equal((await group.locator("#font-file-field > span").first().textContent()).trim(), "皮肤字体")
  assert.match(await group.locator("#font-file-field").getAttribute("title"), /GLOBAL FONT_PATH/)
  assert.match(await group.locator('[data-document-key="FONT_NAME"] .document-field-caption').getAttribute("title"), /系统字体名/)
  assert.equal(await group.locator('input[aria-label="按键文字字号"]').locator("..").locator(".ui-input-affix").textContent(), "px")
  // 字重有自然范围：滑块 + 数值，不是裸输入框。
  assert.equal(await group.locator('[data-document-key="FONT_WEIGHT"] .ui-slider-field').count(), 1)
  // 文字颜色是「正常 | 按下」一行两个色块：色块旁是不透明度 %，点色块弹出取色与色值。
  const swatch = group.getByRole("button", { name: "按键文字颜色正常", exact: true })
  const color = group.locator('input[aria-label="按键文字颜色正常色值"]')
  const alpha = group.locator('input[aria-label="按键文字颜色正常不透明度"]')
  assert.match(await swatch.getAttribute("title"), /^正常 · /)
  assert.match(await group.getByRole("button", { name: "按键文字颜色按下", exact: true }).getAttribute("title"), /^按下 · /)
  const change = async (input, value) => { await input.fill(value); await input.press("Enter") }
  await swatch.click()
  await change(color, "80123456")
  assert.equal(await alpha.inputValue(), "50")
  const picker = group.locator('input[aria-label="按键文字颜色正常取色"]')
  await swatch.click()
  await picker.fill("#abcdef")
  await picker.dispatchEvent("change")
  assert.equal(await color.inputValue(), "80ABCDEF", "changing hue preserves the exact alpha byte")
  await change(alpha, "0")
  assert.equal(await color.inputValue(), "00ABCDEF")
  await change(alpha, "100")
  assert.equal(await color.inputValue(), "FFABCDEF")
  await page.evaluate(async () => (await import("/src/app/edit-history.ts")).undo())
  assert.equal(await color.inputValue(), "00ABCDEF")
  // 字体平滑：布尔值用开关，不写时按开启（百度 StyleParam.f = 1）；关掉写回 0，撤销恢复。
  const cleartype = group.getByRole("switch", { name: "按键文字字体平滑", exact: true })
  assert.equal(await cleartype.count(), 1)
  assert.equal(await cleartype.isChecked(), true)
  await cleartype.click()
  assert.match(await styleText(), /FONT_CLEARTYPE\s*=\s*0/)
  await page.evaluate(async () => (await import("/src/app/edit-history.ts")).undo())
  assert.equal(await cleartype.isChecked(), true)
  // 文字阴影：颜色 + 大小两行；新版百度不绘制，导出时自动切片，这里先确认配置写回皮肤。
  const shadowSwatch = group.getByRole("button", { name: "按键文字阴影颜色", exact: true })
  assert.equal(await shadowSwatch.count(), 1)
  await shadowSwatch.click()
  await change(group.locator('input[aria-label="按键文字阴影颜色色值"]'), "FF000000")
  assert.match(await styleText(), /BORDER_COLOR\s*=\s*FF000000/)
  const shadowSize = group.locator('input[aria-label="按键文字阴影大小"]')
  assert.equal(await shadowSize.locator("..").locator(".ui-input-affix").textContent(), "px")
  await change(shadowSize, "6")
  assert.match(await styleText(), /BORDER_SIZE\s*=\s*6/)
  await page.evaluate(async () => (await import("/src/app/edit-history.ts")).undo())
  await page.evaluate(async () => (await import("/src/app/edit-history.ts")).undo())
  const filterButton = page.locator(".inspector-filter-open")
  await filterButton.click()
  assert.equal(await filterButton.getAttribute("aria-expanded"), "true")
  const filter = page.locator("#inspector-filter")
  await filter.fill("NO_BLUR")
  assert.equal(await page.locator('[data-document-key="NO_BLUR"]').isVisible(), true)
  await filter.press("Escape")
  await filter.press("Escape")
  assert.equal(await filterButton.getAttribute("aria-expanded"), "false")
  // 末尾的分区滚不到检查器顶部：点它必须点亮它自己，不能按滚动位置退回上一个分区。
  const lastButton = page.locator("#mobile-inspector-groups button").last()
  const lastGroup = await lastButton.getAttribute("data-mobile-inspector-group")
  assert.ok(lastGroup, "the last rail button belongs to an inspector group")
  await lastButton.click()
  await page.waitForTimeout(300)
  assert.equal(await page.locator("#quick-inspector").getAttribute("data-mobile-inspector-group"), lastGroup)
  assert.equal(await page.locator("#mobile-inspector-groups button[aria-pressed=\"true\"]").textContent(), await lastButton.textContent())
  const panel = page.locator('#mobile-inspector-groups button', { hasText: "面板" }).first()
  await panel.click()
  const duration = await page.locator('.document-property-section[data-inspector-group-label="面板"]').evaluate(el => el.getAnimations().at(-1)?.effect.getTiming().duration)
  assert.equal(duration, 200)
  await page.emulateMedia({ reducedMotion: "reduce" })
  const reduced = await panel.evaluate(button => {
    button.click()
    const root = document.querySelector("#quick-inspector")
    return getComputedStyle(root).getPropertyValue("--duration-base").trim() === "0ms"
      && document.querySelector('.document-property-section[data-inspector-group-label="面板"]').getAnimations().every(a => a.effect.getTiming().duration === 0)
  })
  assert.equal(reduced, true)
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.evaluate(() => { document.documentElement.dataset.mobilePane = "inspector" })
    assert.equal(await group.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true, "text controls fit the inspector")
  }
  // 选中按键只是换选择对象：右侧停在「动画」分类或「AI 设计」标签时保持该选项。
  await page.setViewportSize({ width: 1440, height: 1000 })
  const canvas = await page.locator("#preview").boundingBox()
  await page.mouse.click(canvas.x + canvas.width * 0.45, canvas.y + canvas.height * 0.45)
  await page.waitForSelector(".key-layout-fields:not([hidden])", { state: "visible" })
  // 选中按键时同一份文字配置按按键编辑，字体平滑同样是开关。
  // 选中按键同样有字体平滑和文字阴影两组配置。
  assert.equal(await page.locator("#key-text-shadow .ui-field").count(), 2)
  const keySmooth = page.locator('.key-typography-fields input[type="checkbox"][aria-label="字体平滑"]')
  assert.equal(await keySmooth.count(), 1)
  await keySmooth.click()
  assert.match(await styleText(), /FONT_CLEARTYPE\s*=\s*0/)
  await page.evaluate(async () => (await import("/src/app/edit-history.ts")).undo())
  await page.locator('#mobile-inspector-groups button', { hasText: "动画" }).first().click()
  await page.mouse.click(canvas.x + canvas.width * 0.6, canvas.y + canvas.height * 0.45)
  await page.waitForTimeout(300)
  assert.equal(await page.locator('#mobile-inspector-groups button[aria-pressed="true"]').textContent(), "动画", "selecting a key keeps the chosen category")
  await page.evaluate(async () => {
    const { appState } = await import("/src/app/state.ts")
    await (await import("/src/app/navigation.ts")).selectFile(appState.archive.names().find((name) => name.endsWith(".css")), "source")
  })
  await page.locator('[data-inspector-tab="ai"]').evaluate((tab) => { tab.hidden = false })
  await page.locator('[data-inspector-tab="ai"]').click()
  await page.mouse.click(canvas.x + canvas.width * 0.45, canvas.y + canvas.height * 0.45)
  await page.waitForTimeout(300)
  assert.equal(await page.locator('[data-inspector-tab="ai"]').getAttribute("aria-selected"), "true", "selecting a key keeps the chosen inspector view")
  assert.deepEqual(errors, [])
  console.log("Inspector polish: compact hints, units, percent alpha precision, undo, filter, navigation motion, reduced motion, narrow layout and view persistence passed")
} finally {
  await browser.close()
  await server.close()
}
