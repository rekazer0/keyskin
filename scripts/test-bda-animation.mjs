import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { bdaAnimationFixture } from '../tests/helpers/bda-animation-fixture.mjs'

const server = await createServer({ root: new URL('..', import.meta.url).pathname, logLevel: 'error', server: { port: 41836, strictPort: false, host: '127.0.0.1', hmr: false } })
await server.listen()
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
const path = 'light/skin/port/animationConfig'
const section = (id) => page.locator(`[data-animation-effect="${id}"]`)
const input = (id, label) => section(id).getByRole('spinbutton', { name: label, exact: true })
const change = async (locator, value) => { await locator.fill(String(value)); await locator.press('Tab') }
const read = () => page.evaluate(async (path) => {
  const { appState } = await import('/src/app/state.ts')
  const { decodedBdaValue } = await import('/src/bda-source.ts')
  return decodedBdaValue(path, appState.archive.getBytes(path))
}, path)
const select = async (path) => {
  await page.evaluate(async (path) => { const { selectFile } = await import('/src/app/navigation.ts'); selectFile(path) }, path)
  await page.waitForSelector('.bda-animation-section')
  await page.waitForTimeout(350)
}

try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  await page.locator('#browser-open').setInputFiles({ name: '动画.bda', mimeType: 'application/octet-stream', buffer: Buffer.from(bdaAnimationFixture()) })
  await page.waitForFunction(() => !document.querySelector('#open').disabled)
  const close = page.locator('#file-operation-dialog[open] #file-operation-close')
  if (await close.isVisible()) await close.click()
  await page.getByRole('button', { name: '编辑模式', exact: true }).click()
  await select(path)
  assert.equal(await page.locator('[data-animation-effect]').count(), 10)
  assert.equal(await page.locator('#mobile-inspector-groups button').count(), 12)
  assert.match(await section('group:press').textContent(), /KEY_Q/)
  assert.equal(await input('shift:move', '结束X（px）最小').inputValue(), '20')

  await change(page.getByRole('spinbutton', { name: '设计宽度', exact: true }), 1242)
  let state = await read()
  assert.equal(state.designWidth, 1242)
  assert.ok(state.effects['shift:move'], 'editing width must not erase the shift map')
  await change(input('alpha:fade', '持续时间'), 420)
  assert.equal((await read()).effects['alpha:fade'].duration, 420)
  await page.evaluate(async () => { (await import('/src/app/edit-history.ts')).undo() })
  assert.equal((await read()).effects['alpha:fade'].duration, 180)
  await page.evaluate(async () => { (await import('/src/app/edit-history.ts')).redo() })
  assert.equal((await read()).effects['alpha:fade'].duration, 420)
  await change(input('shift:move', '结束X（px）最小'), 35)
  assert.deepEqual((await read()).effects['shift:move'].to[0], [35, 30])
  await change(input('emitter:snow', '初始缩放最小'), -0.5)
  assert.deepEqual((await read()).effects['emitter:snow'].scale, [-0.5, 0.75])
  await section('group:press').getByRole('combobox', { name: '组合方式' }).selectOption('1')
  assert.equal((await read()).effects['group:press'].buildMode, 1)
  await change(input('image:spark', '第 2 帧时长'), 600)
  assert.equal((await read()).sequences.spark.frames[1].duration, 600)
  await section('video:movie').getByRole('switch', { name: '结束后移除' }).uncheck()
  assert.equal((await read()).effects['video:movie'].removeOnFinish, false)

  // Consecutive numeric nudges stay on one input and produce one undo entry.
  const duration = input('alpha:fade', '持续时间')
  await duration.focus()
  const count = await page.evaluate(async () => (await import('/src/app/state.ts')).appState.undoStack.length)
  await duration.press('Shift+ArrowUp')
  await duration.press('Shift+ArrowUp')
  await page.waitForTimeout(500)
  assert.equal((await read()).effects['alpha:fade'].duration, 440)
  assert.equal(await page.evaluate(async () => (await import('/src/app/state.ts')).appState.undoStack.length), count + 1)

  assert.ok(await page.locator('.inspector-reset').isVisible())
  await page.locator('.inspector-reset').click()
  state = await read()
  assert.equal(state.designWidth, 1080)
  assert.equal(state.effects['alpha:fade'].duration, 180)
  assert.deepEqual(state.effects['shift:move'].to[0], [20, 30])
  assert.deepEqual(state.effects['emitter:snow'].scale, [0.5, 0.75])
  assert.equal(state.effects['group:press'].buildMode, 0)
  assert.equal(state.sequences.spark.frames[1].duration, 240)
  assert.equal(state.effects['video:movie'].removeOnFinish, true)

  await page.locator('.inspector-filter-open').click()
  await page.locator('#inspector-filter').fill('interpolation')
  assert.equal(await section('alpha:fade').getByRole('combobox', { name: '插值方式' }).isVisible(), true)
  assert.equal(await input('alpha:fade', '持续时间').isVisible(), false)
  await page.locator('#inspector-filter').press('Escape')
  await page.locator('#inspector-filter').press('Escape')
  await section('image:spark').getByRole('button', { name: '播放预览', exact: true }).click()
  await page.waitForFunction(() => Number(document.querySelector('[data-animation-effect="image:spark"] .ui-slider')?.value) > 100)
  await page.waitForTimeout(350)

  await change(input('alpha:fade', '持续时间'), 555)
  const saved = await page.evaluate(async (path) => {
    const { appState } = await import('/src/app/state.ts')
    const { SkinArchive } = await import('/src/skin.ts')
    const { decodedBdaValue } = await import('/src/bda-source.ts')
    const { exportArchive } = await import('/src/app/archive-io.ts')
    const result = await exportArchive('bda')
    const archive = SkinArchive.open(result.bytes, 'bda')
    return { value: decodedBdaValue(path, archive.getBytes(path)), names: archive.names(), text: new TextDecoder().decode(archive.getBytes(path)) }
  }, path)
  assert.equal(saved.value.effects['alpha:fade'].duration, 555)
  assert.equal(Object.keys(saved.value.effects).length, 10)
  assert.ok(saved.names.includes('dark/skin/land/1animationConfig'))
  assert.match(saved.text, /binding-unknown/)
  assert.match(saved.text, /root-unknown/)
  await page.evaluate(async () => {
    const { selectChoice } = await import('/src/app/mobile-layout.ts')
    selectChoice(document.querySelector('#theme'), 'dark')
    selectChoice(document.querySelector('#orientation'), 'land')
  })
  await select('dark/skin/land/lightAnimationConfig')
  await page.getByRole('button', { name: '交互预览', exact: true }).click()
  assert.equal(await page.locator('.bda-animation-section .document-property-field input:enabled, .bda-animation-section .document-property-field select:enabled').count(), 0)
  const box = await page.getByRole('spinbutton', { name: '设计宽度' }).boundingBox()
  await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2)
  await page.waitForSelector('#edit-mode-dialog[open]')
  assert.deepEqual(errors, [])
  console.log('BDA animation: 10 effect types, width/maps, floats, editing, undo/redo, reset, filtering, playback, gestures, export/reopen, themes/orientations and readonly passed')
} finally { await browser.close(); await server.close() }
