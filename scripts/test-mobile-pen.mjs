import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { mobileFigmaFixture } from '../tests/helpers/mobile-figma-fixture.mjs'

const root = new URL('..', import.meta.url).pathname
const output = `${root}.ui-current/mobile-pen`
mkdirSync(output, { recursive: true })
const server = await createServer({ root, logLevel: 'error', server: { host: '127.0.0.1', port: 41768, strictPort: false, hmr: false } })
await server.listen()
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 393, height: 852 }, isMobile: true, hasTouch: true })
const errors = [], captures = []
page.on('pageerror', error => errors.push(error.message))
await page.addInitScript(() => localStorage.setItem('onboarding-tour-v1', 'done'))
const capture = async name => {
  await page.evaluate(async () => {
    await document.fonts.ready
    for (const animation of document.getAnimations()) if (Number.isFinite(animation.effect?.getComputedTiming().endTime)) animation.finish()
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
  })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${name}: no horizontal overflow`)
  await page.screenshot({ path: `${output}/${name}.png`, animations: 'disabled' })
  captures.push(name)
}
const select = async () => {
  await page.evaluate(async () => {
    const { selectFile } = await import('/src/app/navigation.ts')
    selectFile('light/skin/port/py_26.ini')
    const { appState } = await import('/src/app/state.ts')
    appState.selectedKeySections = ['KEY11']
    const { preview } = await import('/src/app/canvas-interaction.ts')
    preview.setSelected(['KEY11'])
    ;(await import('/src/app/key-inspector.ts')).populateKeyInspector()
    ;(await import('/src/app/mobile-layout.ts')).setMobilePane('inspector')
  })
}
const close = async () => {
  const dialog = page.locator('dialog[open]').last()
  await dialog.evaluate(node => node.dispatchEvent(new Event('cancel', { cancelable: true })))
  await dialog.waitFor({ state: 'hidden' })
}
const snapshot = () => page.evaluate(async () => {
  const { appState } = await import('/src/app/state.ts')
  return { depth: appState.undoStack.length, layout: appState.archive.getText('light/skin/port/py_26.ini'), animation: appState.archive.getText('light/skin/res/anim.ini') }
})
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  await page.locator('#mobile-welcome-new').waitFor()
  assert.equal(await page.locator('.mobile-welcome-hero h1').textContent(), '键设')
  assert.equal(await page.locator('#mobile-navigation button').count(), 5)
  assert.equal((await page.locator('#mobile-welcome-new').boundingBox()).height, 108)
  await page.locator('#mobile-welcome-blank').click()
  await page.locator('#new-project-dialog[open]').waitFor()
  await close()
  await capture('home-empty')
  await page.locator('#browser-open').setInputFiles({ name: '薄雾蓝.bdi', mimeType: 'application/octet-stream', buffer: Buffer.from(mobileFigmaFixture()) })
  await page.waitForFunction(() => !document.querySelector('#open').disabled && !document.querySelector('.canvas-wrap').classList.contains('empty'))
  if (await page.locator('#file-operation-dialog[open]').count()) await page.locator('#file-operation-close').click()
  await select()
  await capture('editor')
  const before = await snapshot()
  await page.locator('#mobile-navigation [data-mobile-page=home]').click()
  assert.equal(await page.locator('#mobile-welcome-resume img').count(), 1, 'resume uses the current real canvas')
  assert.equal(await page.locator('#mobile-welcome-resume .template-name').textContent(), '薄雾蓝')
  await capture('home-resume')
  await page.locator('#mobile-welcome-resume button').click()
  assert.deepEqual(await snapshot(), before, 'resume keeps the current document and undo history')
  await page.locator('#mobile-property-tabs [data-mobile-category=appearance]').click()
  await capture('inspector')
  await page.locator('.mobile-appearance-heading button').click()
  await page.locator('#picker-dialog[open]').waitFor()
  const picker = page.frameLocator('#picker-frame')
  await picker.locator('#style-library-grid .ui-style-card').first().waitFor()
  assert.equal(await picker.locator('#picker-title').textContent(), '选择样式')
  const bounds = await page.locator('#picker-dialog').boundingBox()
  assert.ok(bounds.y > 200 && bounds.y + bounds.height <= 853, 'style picker is a bottom sheet')
  await capture('style-sheet')
  await picker.locator('#style-library-grid .ui-style-card').first().click()
  await picker.locator('#style-library-cancel').click()
  await page.locator('#picker-dialog').waitFor({ state: 'hidden' })
  assert.deepEqual(await snapshot(), before, 'cancelled appearance selection leaves all data unchanged')
  await page.locator('#mobile-property-tabs [data-mobile-category=animation]').click()
  await page.locator('.key-animation-fields .ui-style-state').first().click()
  await page.getByRole('dialog', { name: '选择动效', exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelector('.ui-mobile-motion-picker .ui-animation-stage canvas')?.getBoundingClientRect().height > 0)
  await capture('motion-sheet')
  const motionFooter = await page.locator('.ui-mobile-motion-picker .ui-dialog-footer').boundingBox()
  assert.ok(motionFooter.y + motionFooter.height <= 852, 'motion actions stay within the viewport')
  const motionDuration = await page.locator('.ui-mobile-motion-parameters input[type=number]').boundingBox()
  assert.ok(motionDuration.y + motionDuration.height <= motionFooter.y, 'duration is fully visible above the motion actions')
  await page.locator('.ui-mobile-motion-list [data-motion-style="5"]').click()
  await page.locator('.ui-mobile-motion-parameters input[type=number]').fill('500')
  await page.locator('.ui-mobile-motion-parameters input[type=number]').dispatchEvent('change')
  await close()
  assert.deepEqual(await snapshot(), before, 'cancelled motion selection and duration leave the document unchanged')
  await page.locator('.key-animation-fields .ui-style-state').first().click()
  await page.getByRole('dialog', { name: '选择动效', exact: true }).waitFor()
  await page.locator('.ui-mobile-motion-list [data-motion-style="5"]').click()
  const duration = page.locator('.ui-mobile-motion-parameters input[type=number]')
  await duration.fill('360')
  await duration.dispatchEvent('change')
  await page.getByRole('dialog', { name: '选择动效', exact: true }).getByRole('button', { name: '应用', exact: true }).click()
  await page.locator('.ui-mobile-motion-picker').waitFor({ state: 'detached' })
  assert.match((await snapshot()).animation, /DURATION=360/)
  assert.match((await snapshot()).layout, /ANIM_STYLE=5/, 'the new motion is bound to the selected key')
  assert.equal((await snapshot()).depth, before.depth + 1, 'binding and duration form one undo step')
  await page.evaluate(async () => (await import('/src/app/edit-history.ts')).undo())
  assert.deepEqual(await snapshot(), before, 'one undo restores binding and animation duration')
  await page.locator('#mobile-navigation [data-mobile-page=resources]').click()
  await page.locator('.mobile-resource-heading').waitFor()
  assert.match(await page.locator('#mobile-resource-summary').textContent(), /共 \d+ 个资源/)
  assert.equal(await page.locator('#mobile-resource-tabs button small').count(), 3)
  assert.ok((await page.locator('#resource-gallery').boundingBox()).height > 160, 'style cards retain usable screen space')
  assert.ok(await page.locator('#resource-gallery .ui-style-card').first().isVisible(), 'real style cards are visible')
  await capture('resources-styles')
  await page.locator('[data-mobile-resource=resource]').click()
  await capture('resources-images')
  await page.locator('[data-mobile-resource=sound]').click()
  await capture('resources-sounds')
  await page.locator('#mobile-navigation [data-mobile-page=ai]').click()
  await capture('ai')
  await page.locator('#mobile-navigation [data-app-dialog=settings]').click()
  await page.locator('.mobile-settings-overview').waitFor()
  assert.equal(await page.locator('#settings-dialog #mobile-navigation').count(), 1, 'settings reuses the same bottom navigation')
  assert.equal(await page.locator('.mobile-settings-group').count(), 4)
  await capture('settings')
  await page.locator('.mobile-settings-group').last().scrollIntoViewIfNeeded()
  await capture('settings-bottom')
  await page.locator('.mobile-settings-group').first().scrollIntoViewIfNeeded()
  const originalTheme = await page.locator('#app-theme').inputValue()
  await page.locator('[data-setting-choice=app-theme][data-value=dark]').click()
  await capture('settings-dark')
  await page.locator('#settings-cancel').click()
  await page.locator('#settings-dialog').waitFor({ state: 'hidden' })
  assert.equal(await page.locator('#app-theme').inputValue(), originalTheme, 'cancel restores the opening theme')
  await page.locator('#mobile-navigation [data-app-dialog=settings]').click()
  await page.getByRole('button', { name: '更多外观设置', exact: true }).click()
  assert.equal(await page.locator('#settings-panel-appearance #app-theme').count(), 1, 'detail restores the original controls')
  await page.locator('.mobile-settings-back').click()
  await page.locator('#mobile-navigation [data-mobile-page=home]').click()
  await page.locator('#settings-dialog').waitFor({ state: 'hidden' })
  assert.equal(await page.locator('#mobile-navigation [aria-current=page]').getAttribute('data-mobile-page'), 'home')
  for (const width of [320, 393, 430]) {
    await page.setViewportSize({ width, height: 852 })
    await capture(`home-${width}`)
    await page.locator('#mobile-navigation [data-mobile-page=edit]').click()
    await select()
    await capture(`editor-${width}`)
    await page.locator('#mobile-navigation [data-mobile-page=resources]').click()
    await capture(`resources-${width}`)
    await page.locator('#mobile-navigation [data-mobile-page=home]').click()
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.locator('#mobile-navigation [data-mobile-page=edit]').evaluate(button => button.click())
  await page.locator('#workspace-navigation [data-app-dialog=settings]').click()
  assert.equal(await page.locator('#settings-panel-appearance #app-theme').count(), 1)
  assert.equal(await page.locator('.mobile-settings-overview').isVisible(), false, 'desktop retains its settings layout')
  await close()
  assert.deepEqual(errors, [])
  writeFileSync(`${output}/result.json`, JSON.stringify({ passed: true, captures, errors }, null, 2))
  console.log('PASS mobile Pen: eight screens, real previews, responsive layouts, settings rollback and atomic motion undo')
} catch (error) {
  console.error('Browser errors:', errors)
  console.error(await page.evaluate(() => ({ page: document.documentElement.dataset, dialogs: [...document.querySelectorAll('dialog[open]')].map(node => node.getAttribute('aria-label')) })))
  console.error(await page.locator('#resource-list-view, #resource-list-view > *, .resource-filters > *, .ui-style-filter-bar > *').evaluateAll(nodes => nodes.map(node => ({ node: node.id || node.className, height: node.getBoundingClientRect().height, display: getComputedStyle(node).display, flex: getComputedStyle(node).flex, order: getComputedStyle(node).order }))))
  await page.screenshot({ path: `${output}/failure.png`, animations: 'disabled' })
  throw error
} finally {
  await browser.close()
  await server.close()
}
