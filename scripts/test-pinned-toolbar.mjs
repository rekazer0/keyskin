import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { bdsFixture } from '../tests/helpers/baidu-fixture.mjs'

const server = await createServer({ logLevel: 'error', server: { host: '127.0.0.1', port: 41821, strictPort: false, hmr: false } })
await server.listen()
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => localStorage.setItem('onboarding-tour-v1', 'done'))
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  const openSkin = async () => {
    await page.locator('#browser-open').setInputFiles({ name: '固定工具.bds', mimeType: 'application/octet-stream', buffer: Buffer.from(bdsFixture()) })
    await page.waitForSelector('#workspace-tools-open:enabled')
  }
  await openSkin()
  await page.waitForSelector('#pinned-toolbar[data-editing="false"]')
  const toolbar = page.locator('#pinned-toolbar')
  const actions = toolbar.locator('.ui-pinned-tool')
  const button = toolbar.locator('.ui-pinned-tool > button:first-child')
  const drag = async (source, target = toolbar, fromLeft = false) => {
    const from = await source.boundingBox()
    const to = await target.boundingBox()
    await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
    await page.mouse.down()
    await page.mouse.move(to.x + (fromLeft ? 2 : to.width / 2), to.y + to.height / 2, { steps: 10 })
    const preview = await page.locator('.ui-toolbar-drag-preview').boundingBox()
    assert.ok(preview, 'dragging page actions creates a preview')
    await page.mouse.up()
  }
  const settings = page.locator("#workspace-navigation [data-settings-entry='settings']")
  await drag(settings)
  assert.equal(await actions.count(), 1)
  assert.equal(await page.locator('#settings-workspace').isVisible(), false, 'drag does not invoke the action')
  await drag(settings)
  assert.equal(await actions.count(), 1, 'duplicate pins are ignored')
  await drag(settings, page.locator('.canvas-wrap'))
  assert.equal(await actions.count(), 1, 'drop outside cancels')
  await button.click()
  await page.locator('#settings-workspace').waitFor({ state: 'visible' })
  await page.keyboard.press('Escape')
  await page.locator('#settings-workspace').waitFor({ state: 'hidden' })
  await button.focus()
  await page.keyboard.press('F2')
  assert.equal(await toolbar.getAttribute('data-editing'), 'true')
  assert.equal(await button.evaluate(node => getComputedStyle(node).animationName), 'ui-toolbar-edit')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await button.evaluate(node => getComputedStyle(node).animationDuration), '0s')
  await page.keyboard.press('Escape')
  await page.reload()
  await openSkin()
  await page.waitForSelector('.ui-pinned-tool')
  assert.equal(await actions.count(), 1, 'pins survive reload')
  await button.focus()
  await page.keyboard.press('F2')
  await toolbar.locator('.ui-pinned-tool-remove').click({ force: true })
  assert.equal(await actions.count(), 0)
  assert.equal(await page.locator("#workspace-navigation [data-settings-entry='settings']").count(), 1, 'original action remains')

  const toolsOpen = page.locator('#workspace-tools-open')
  await page.locator('[data-mode-choice="preview"]').click()
  await toolsOpen.click()
  const tools = page.locator('#workspace-tools-dialog')
  const grid = tools.locator('.ui-tool-grid')
  const cards = grid.locator('button[data-workspace-tool]')
  const order = () => actions.evaluateAll(nodes => nodes.map(node => node.dataset.toolbarAction))
  const pinned = key => toolbar.locator(`.ui-pinned-tool[data-toolbar-action="${key}"]`)
  await tools.locator('#pinned-toolbar').waitFor()
  const assertSpotlight = async (surface, bar) => {
    const panel = await surface.boundingBox()
    const slot = await bar.boundingBox()
    assert.ok(slot.width > 0 && slot.x >= 0 && slot.y >= 0 && slot.y + slot.height <= panel.y, `spotlight leaves the toolbar and dialog title visible: ${JSON.stringify({ panel, slot })}`)
  }
  await assertSpotlight(tools, toolbar)
  const tiles = await cards.evaluateAll(nodes => nodes.map(node => {
    const { width, height } = node.getBoundingClientRect()
    return Math.abs(width - height)
  }))
  assert.equal(tiles.length, 7)
  assert.ok(tiles.every(delta => delta < 1), 'all tool tiles are square')
  const keys = await cards.evaluateAll(nodes => nodes.map(node => node.dataset.workspaceTool))
  assert.equal(await tools.locator('[data-workspace-tool="panel-scale"]').isDisabled(), true)
  assert.equal(await tools.getByRole('button', { name: '分享到 ADB' }).isDisabled(), true, 'web does not enable ADB')
  for (const [index, key] of keys.entries()) {
    await drag(cards.nth(index), toolbar, true)
    assert.equal(await pinned(key).count(), 1, `can pin ${key}, even when unavailable`)
    assert.equal(await tools.isVisible(), true, 'dragging does not execute the tool')
  }
  assert.equal(await actions.count(), 7)
  assert.equal(await pinned('adb-share').locator('button').first().isDisabled(), true)
  await cards.filter({ hasText: '分享到 ADB' }).focus()
  await page.keyboard.press('Enter')
  assert.equal(await tools.isVisible(), true, 'a disabled tool does not execute')
  await page.setViewportSize({ width: 880, height: 480 })
  await assertSpotlight(tools, toolbar)
  await page.setViewportSize({ width: 1440, height: 900 })
  await drag(pinned('save'), toolbar, true)
  assert.equal((await order())[0], 'save', 'can reorder inside the modal')
  const reordered = await order()
  await drag(pinned('adb-share'), tools.locator('.ui-dialog-header'))
  assert.deepEqual(await order(), reordered, 'dropping outside the grid and toolbar cancels')
  assert.match(await tools.evaluate(node => getComputedStyle(node, '::backdrop').backgroundImage), /linear-gradient/)
  await page.screenshot({ path: '.ui-current/workspace-tools-toolbar.png', animations: 'disabled' })
  for (const key of keys) {
    await drag(pinned(key), grid)
    assert.equal(await pinned(key).count(), 0, `can drag ${key} back, even when unavailable`)
  }
  assert.equal(await cards.count(), 7, 'removing pins does not delete tools')
  await drag(cards.filter({ hasText: /^保存/ }))
  await tools.locator('[data-workspace-tool="mobile-export-open"]').focus()
  await page.keyboard.press('Alt+Enter')
  assert.deepEqual(await order(), ['save', 'mobile-export-open'])
  await page.keyboard.press('Escape')
  await tools.waitFor({ state: 'hidden' })
  assert.equal(await toolsOpen.evaluate(node => node === document.activeElement), true, 'closing restores focus')
  await drag(pinned('mobile-export-open'), toolbar, true)
  assert.deepEqual(await order(), ['mobile-export-open', 'save'], 'dragging a pinned tool changes its position')
  await drag(pinned('save'), page.locator('.canvas-wrap'))
  assert.deepEqual(await order(), ['mobile-export-open', 'save'], 'dropping outside does not change the order')
  await page.locator('#pinned-toolbar [data-toolbar-action="mobile-export-open"] button:first-child').click()
  const share = page.locator('#share-dialog')
  await share.waitFor({ state: 'visible' })
  assert.equal(await page.locator('#file-operation-dialog[open]').count(), 0, 'clicking export goes straight to format selection without saving')
  await page.keyboard.press('Escape')
  await share.waitFor({ state: 'hidden' })
  await page.reload()
  await openSkin()
  await toolbar.locator('[data-toolbar-action="save"]').waitFor()
  assert.deepEqual(await order(), ['mobile-export-open', 'save'], 'reordering persists across reload')
  await button.first().focus()
  await page.keyboard.press('Alt+ArrowRight')
  assert.deepEqual(await order(), ['save', 'mobile-export-open'], 'keyboard can also reorder the tools')
  await page.keyboard.press('F2')
  await page.keyboard.press('Backspace')
  assert.deepEqual(await order(), ['save', 'mobile-export-open'])
  await page.keyboard.press('Delete')
  assert.deepEqual(await order(), ['save'])
  await page.keyboard.press('Escape')
  const clockStart = Date.now()
  await page.clock.install({ time: clockStart })
  await page.clock.pauseAt(clockStart + 1000)
  const box = await button.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.clock.runFor(1999)
  assert.equal(await toolbar.getAttribute('data-editing'), 'false')
  await page.clock.runFor(1)
  assert.equal(await toolbar.getAttribute('data-editing'), 'true', 'two-second hold enters edit mode')
  await page.mouse.up()
  await page.clock.runFor(1)
  await page.clock.resume()
  await page.keyboard.press('Escape')
  await page.evaluate(() => {
    window.showSaveFilePicker = async () => ({
      name: '固定工具.bds',
      createWritable: async () => ({ write: async bytes => { window.savedBytes = bytes.byteLength }, close: async () => {} }),
    })
  })
  await button.click()
  await share.locator('#file-operation-dialog[data-outcome="success"]').waitFor()
  assert.ok(await page.evaluate(() => window.savedBytes > 0), 'single click runs the original save in the shared modal')
  await share.locator('#file-operation-close').click()
  await page.keyboard.press('Escape')
  await share.waitFor({ state: 'hidden' })
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  }
  const phone = await browser.newPage({ viewport: { width: 320, height: 568 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
  await phone.addInitScript(() => localStorage.setItem('onboarding-tour-v1', 'done'))
  await phone.goto(page.url())
  await phone.locator('#browser-open').setInputFiles({ name: '触控工具.bds', mimeType: 'application/octet-stream', buffer: Buffer.from(bdsFixture()) })
  await phone.waitForFunction(() => !document.querySelector('#workspace-tools-open').disabled)
  if (await phone.locator('.mobile-route-close').isVisible()) {
    await phone.locator('#mobile-project-toggle').tap()
    await phone.locator('#mobile-project-dialog [data-path="light/skin/port/py_26.ini"]').tap()
    await phone.locator('#mobile-project-dialog').waitFor({ state: 'hidden' })
  }
  await phone.locator('#mobile-app-more > summary').tap()
  await phone.locator('[data-mobile-action="workspace-tools-open"]').tap()
  const phoneTools = phone.locator('#workspace-tools-dialog[data-toolbar-spotlight="true"]')
  await phoneTools.waitFor()
  const cdp = await phone.context().newCDPSession(phone)
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] })
  const touchDrag = async (source, target) => {
    const start = await source.boundingBox()
    const end = await target.boundingBox()
    await touch('touchStart', start.x + start.width / 2, start.y + start.height / 2)
    await touch('touchMove', end.x + end.width / 2, end.y + end.height / 2)
    await touch('touchEnd')
  }
  const phoneToolbar = phone.locator('#pinned-toolbar')
  const phonePin = phoneToolbar.locator('[data-toolbar-action="save"]')
  await assertSpotlight(phoneTools, phoneToolbar)
  await touchDrag(phoneTools.locator('[data-workspace-tool="save"]'), phoneToolbar)
  assert.equal(await phone.locator('#pinned-toolbar [data-toolbar-action="save"]').count(), 1, 'touch drag can pin a tool')
  assert.equal(await phoneTools.isVisible(), true, 'touch drag does not execute the tool')
  await phone.screenshot({ path: '.ui-current/workspace-tools-toolbar-mobile.png', animations: 'disabled' })
  await touchDrag(phonePin, phoneTools.locator('.ui-tool-grid'))
  assert.equal(await phonePin.count(), 0, 'touch drag back removes the pin')
  await phone.close()
  assert.deepEqual(errors, [])
  console.log('Pinned toolbar: all seven tools can be pinned, reordered and dragged back; desktop, touch, disabled actions, persistence and keyboard passed')
} finally {
  await browser.close()
  await server.close()
}
