import assert from "node:assert/strict"
import { chromium } from "playwright"
import { createServer } from "vite"

const server = await createServer({ logLevel: "error", server: { host: "127.0.0.1", port: 41821, strictPort: false } })
await server.listen()
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  await page.addInitScript(() => localStorage.setItem("onboarding-tour-v1", "done"))
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  await page.waitForSelector('#pinned-toolbar[data-editing="false"]')
  await page.clock.install()
  const toolbar = page.locator("#pinned-toolbar")
  const menu = page.locator(".pen-file-menu > summary")
  const actions = toolbar.locator(".ui-pinned-tool")
  const editing = () => toolbar.getAttribute("data-editing")
  const assertAligned = async () => {
    const geometry = await page.evaluate(() => {
      const menu = document.querySelector(".pen-file-menu > summary").getBoundingClientRect()
      return [...document.querySelectorAll(".ui-pinned-tool:not([hidden])")].map(item => {
        const bounds = item.getBoundingClientRect()
        const button = item.querySelector("button").getBoundingClientRect()
        return { centerDelta: bounds.y + bounds.height / 2 - menu.y - menu.height / 2,
          buttonCenterDelta: button.y + button.height / 2 - menu.y - menu.height / 2,
          heightDelta: bounds.height - menu.height }
      })
    })
    for (const { centerDelta, buttonCenterDelta, heightDelta } of geometry) {
      assert.ok(Math.abs(centerDelta) < 0.1 && Math.abs(buttonCenterDelta) < 0.1, "pinned buttons share the menu's vertical center")
      assert.ok(Math.abs(heightDelta) < 0.1, "pinned buttons have no extra text-baseline space")
    }
  }
  const drag = async (selector, drop = true) => {
    await menu.click()
    await page.waitForTimeout(250)
    const from = await page.locator(selector).boundingBox()
    const to = await toolbar.boundingBox()
    await page.mouse.move(from.x + 12, from.y + from.height / 2)
    await page.mouse.down()
    await page.mouse.move(to.x + to.width / 2, drop ? to.y + to.height / 2 : 200, { steps: 10 })
    const preview = await page.locator(".ui-toolbar-drag-preview").boundingBox()
    assert.ok(Math.abs(preview.x + preview.width / 2 - to.x - to.width / 2) < 0.1
      && Math.abs(preview.y + preview.height / 2 - (drop ? to.y + to.height / 2 : 200)) < 0.1, "drag preview stays centered under the pointer")
    await page.mouse.up()
    await page.clock.runFor(1)
  }
  await drag('.pen-file-menu [data-app-dialog="settings"]')
  assert.equal(await actions.count(), 1, "drag pins menu icon")
  await assertAligned()
  const originalItem = await actions.first().elementHandle()
  assert.equal(await page.locator("#settings-dialog").evaluate(node => node.open), false, "drag does not invoke action")
  await drag('.pen-file-menu [data-app-dialog="settings"]')
  assert.equal(await actions.count(), 1, "duplicate pin is ignored")
  await drag("#new", false)
  assert.equal(await actions.count(), 1, "dropping outside cancels")
  await page.keyboard.press("Escape")
  await toolbar.getByRole("button", { name: "设置…", exact: true }).click()
  await page.locator("#settings-dialog").waitFor({ state: "visible" })
  await page.keyboard.press("Escape")
  await page.clock.runFor(1000)
  await page.locator("#settings-dialog").waitFor({ state: "hidden", timeout: 2000 })
  const button = toolbar.locator(".ui-pinned-tool > button:first-child")
  const box = await button.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.clock.runFor(1999)
  assert.equal(await editing(), "false", "long press does not fire before two seconds")
  await page.clock.runFor(1)
  assert.equal(await editing(), "true", "two seconds enters edit mode")
  assert.equal(await button.evaluate(node => getComputedStyle(node).animationName), "ui-toolbar-edit")
  assert.equal(await originalItem.evaluate(node => node === document.querySelector(".ui-pinned-tool")), true, "entering edit mode preserves the original item")
  const motion = await button.evaluateHandle(node => node.getAnimations().find(animation => animation.animationName === "ui-toolbar-edit"))
  await page.locator("#save").evaluate(node => { node.disabled = false })
  assert.equal(await button.evaluate((node, animation) => node.getAnimations().includes(animation), motion), true, "menu state updates do not restart the editing animation")
  await page.locator("#save").evaluate(node => { node.disabled = true })
  const samples = await button.evaluate(node => {
    const animation = node.getAnimations().find(animation => animation.animationName === "ui-toolbar-edit")
    const duration = animation.effect.getTiming().duration
    const previousTime = animation.currentTime
    animation.pause()
    const samples = [0, 0.25, 0.5, 0.75, 1].map(fraction => {
      animation.currentTime = duration * fraction
      const transform = new DOMMatrix(getComputedStyle(node).transform)
      return { angle: Math.atan2(transform.b, transform.a) * 180 / Math.PI,
        remove: node.parentElement.querySelector(".ui-pinned-tool-remove").getBoundingClientRect().toJSON() }
    })
    animation.currentTime = previousTime
    animation.play()
    return samples
  })
  assert.ok(samples.some(sample => Math.abs(sample.angle) > 1), "editing animation still wobbles")
  assert.ok(samples.every(sample => Math.abs(sample.angle) <= 1.51), "editing wobble stays subtle")
  assert.ok(samples.every(sample => JSON.stringify(sample.remove) === JSON.stringify(samples[0].remove)), "remove button stays fixed throughout the wobble")
  await assertAligned()
  await page.mouse.move(box.x + box.width + 10, box.y + box.height / 2)
  await page.mouse.up()
  await page.clock.runFor(1)
  assert.equal(await page.evaluate(async () => (await import("/src/app/state.ts")).appState.pinnedToolbar.suppressClick), false, "moving after long press does not block later clicks")
  assert.equal(await page.locator("#settings-dialog").evaluate(node => node.open), false, "long press does not invoke action")
  await button.click({ force: true })
  assert.equal(await page.locator("#settings-dialog").evaluate(node => node.open), false, "edit mode suppresses actions")
  await page.keyboard.press("Escape")
  assert.equal(await editing(), "false")
  await page.reload()
  await page.waitForSelector('#pinned-toolbar[data-editing="false"]')
  assert.equal(await actions.count(), 1, "pins persist after reload")
  await button.focus()
  await page.keyboard.press("F2")
  await toolbar.getByRole("button", { name: "从工具栏移除设置…" }).click({ force: true })
  assert.equal(await actions.count(), 0, "corner x removes pin")
  assert.equal(await page.locator('.pen-file-menu [data-app-dialog="settings"]').count(), 1, "menu action remains")
  await drag("#save")
  assert.equal(await actions.count(), 1, "disabled menu entries can be pinned")
  assert.equal(await button.isDisabled(), true, "disabled state is preserved")
  await page.locator("#save").evaluate(node => { node.disabled = false })
  await page.waitForFunction(() => !document.querySelector(".ui-pinned-tool > button").disabled)
  assert.equal(await button.isDisabled(), false, "state follows original menu")
  await page.locator("#save").evaluate(node => { node.disabled = true })
  await page.waitForFunction(() => document.querySelector(".ui-pinned-tool > button").disabled)
  await actions.first().focus()
  await page.keyboard.press("F2")
  await page.keyboard.press("Delete")
  assert.equal(await actions.count(), 0, "disabled pins can be removed with keyboard")
  await menu.click()
  await page.locator("#new").focus()
  await page.keyboard.press("Alt+Enter")
  assert.equal(await actions.count(), 1, "keyboard can pin menu actions")
  await button.focus()
  await page.keyboard.press("F2")
  await page.mouse.click(800, 200)
  assert.equal(await editing(), "false", "outside click exits edit mode")
  await page.emulateMedia({ reducedMotion: "reduce" })
  await button.focus()
  await page.keyboard.press("F2")
  assert.equal(await button.evaluate(node => getComputedStyle(node).animationDuration), "0s", "reduced motion stops wobble")
  await page.keyboard.press("Escape")
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "mobile toolbar does not overflow")
    await assertAligned()
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.emulateMedia({ reducedMotion: "no-preference" })
  await button.focus()
  await page.keyboard.press("F2")
  await page.screenshot({ path: "/tmp/keyskin-pinned-toolbar.png" })
  await page.keyboard.press("Escape")
  for (const selector of ["#open", '.pen-file-menu [data-app-dialog="settings"]']) {
    await menu.click()
    await page.locator(selector).focus()
    await page.keyboard.press("Alt+Enter")
  }
  await button.first().focus()
  await page.keyboard.press("F2")
  const survivor = await actions.last().elementHandle()
  const survivorMotion = await survivor.evaluateHandle(node => node.querySelector("button").getAnimations().find(animation => animation.animationName === "ui-toolbar-edit"))
  await actions.first().locator(".ui-pinned-tool-remove").click({ force: true })
  assert.equal(await survivor.evaluate((node, animation) => node.isConnected && node.querySelector("button").getAnimations().includes(animation), survivorMotion), true, "removing a neighbor preserves existing nodes and animation progress")
  await assertAligned()
  assert.deepEqual(errors, [])
  const touchPage = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  await touchPage.addInitScript(() => localStorage.setItem("onboarding-tour-v1", "done"))
  await touchPage.goto(page.url())
  await touchPage.waitForSelector('#new[data-toolbar-action]', { state: "attached" })
  await touchPage.locator(".pen-file-menu > summary").tap()
  await touchPage.waitForTimeout(250)
  const icon = await touchPage.locator("#new [data-icon]").boundingBox()
  const cdp = await touchPage.context().newCDPSession(touchPage)
  await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: icon.x + icon.width / 2, y: icon.y + icon.height / 2 }] })
  await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: 90, y: 60 }] })
  const touchTarget = await touchPage.locator("#pinned-toolbar").boundingBox()
  assert.ok(touchTarget.width > 0, "first touch drag reveals empty mobile drop target")
  await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: touchTarget.x + touchTarget.width / 2, y: touchTarget.y + touchTarget.height / 2 }] })
  await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] })
  assert.equal(await touchPage.locator(".ui-pinned-tool").count(), 1, "touch drag pins menu icon")
  await touchPage.clock.install()
  const touchButton = await touchPage.locator(".ui-pinned-tool > button:first-child").boundingBox()
  await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: touchButton.x + touchButton.width / 2, y: touchButton.y + touchButton.height / 2 }] })
  await touchPage.clock.runFor(2000)
  assert.equal(await touchPage.locator("#pinned-toolbar").getAttribute("data-editing"), "true", "touch long press enters edit mode")
  await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] })
  await touchPage.clock.runFor(1)
  await touchPage.locator(".ui-pinned-tool-remove").tap({ force: true })
  assert.equal(await touchPage.locator(".ui-pinned-tool").count(), 0, "touch x removes pin")
  await touchPage.close()
  console.log("Pinned toolbar: drag, cancel, duplicate, persistence, two-second press, editing, removal, state sync, keyboard and reduced motion passed")
} finally {
  await browser.close()
  await server.close()
}
