import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { bdsFixture } from '../tests/helpers/baidu-fixture.mjs'

const server = await createServer({ logLevel: 'error', server: { host: '127.0.0.1', port: 41821, strictPort: false, hmr: false } })
await server.listen()
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => localStorage.setItem('onboarding-tour-v1', 'done'))
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  await page.waitForSelector('#pinned-toolbar[data-editing="false"]')
  const toolbar = page.locator('#pinned-toolbar')
  const actions = toolbar.locator('.ui-pinned-tool')
  const button = toolbar.locator('.ui-pinned-tool > button:first-child')
  const drag = async (selector, drop = true) => {
    const from = await page.locator(selector).boundingBox()
    const to = await toolbar.boundingBox()
    await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
    await page.mouse.down()
    await page.mouse.move(to.x + to.width / 2, drop ? to.y + to.height / 2 : 200, { steps: 10 })
    const preview = await page.locator('.ui-toolbar-drag-preview').boundingBox()
    assert.ok(preview, 'dragging page actions creates a preview')
    await page.mouse.up()
  }
  await drag("#workspace-navigation [data-app-dialog='settings']")
  assert.equal(await actions.count(), 1)
  assert.equal(await page.locator('#settings-dialog').isVisible(), false, 'drag does not invoke the action')
  await drag("#workspace-navigation [data-app-dialog='settings']")
  assert.equal(await actions.count(), 1, 'duplicate pins are ignored')
  await drag("#workspace-navigation [data-app-dialog='settings']", false)
  assert.equal(await actions.count(), 1, 'drop outside cancels')
  await button.click()
  await page.locator('#settings-dialog').waitFor({ state: 'visible' })
  await page.keyboard.press('Escape')
  await page.locator('#settings-dialog').waitFor({ state: 'hidden' })
  await button.focus()
  await page.keyboard.press('F2')
  assert.equal(await toolbar.getAttribute('data-editing'), 'true')
  assert.equal(await button.evaluate(node => getComputedStyle(node).animationName), 'ui-toolbar-edit')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await button.evaluate(node => getComputedStyle(node).animationDuration), '0s')
  await page.keyboard.press('Escape')
  await page.reload()
  await page.waitForSelector('.ui-pinned-tool')
  assert.equal(await actions.count(), 1, 'pins survive reload')
  await button.focus()
  await page.keyboard.press('F2')
  await toolbar.locator('.ui-pinned-tool-remove').click({ force: true })
  assert.equal(await actions.count(), 0)
  assert.equal(await page.locator("#workspace-navigation [data-app-dialog='settings']").count(), 1, 'original action remains')

  await page.locator('#browser-open').setInputFiles({ name: '固定工具.bds', mimeType: 'application/octet-stream', buffer: Buffer.from(bdsFixture()) })
  await page.waitForFunction(() => !document.querySelector('#open').disabled)
  await page.locator('#workspace-export').click()
  await page.locator('#save').evaluate(node => { node.disabled = true })
  await drag('#save')
  assert.equal(await actions.count(), 1, 'disabled page actions can be pinned')
  assert.equal(await button.isDisabled(), true)
  await page.locator('#save').evaluate(node => { node.disabled = false })
  await page.waitForFunction(() => !document.querySelector('.ui-pinned-tool > button').disabled)
  await button.focus()
  await page.keyboard.press('F2')
  await page.keyboard.press('Delete')
  assert.equal(await actions.count(), 0)
  await page.locator('#save').focus()
  await page.keyboard.press('Alt+Enter')
  assert.equal(await actions.count(), 1, 'keyboard pins page actions')
  await page.clock.install()
  const box = await button.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.clock.runFor(1999)
  assert.equal(await toolbar.getAttribute('data-editing'), 'false')
  await page.clock.runFor(1)
  assert.equal(await toolbar.getAttribute('data-editing'), 'true', 'two-second hold enters edit mode')
  await page.mouse.up()
  await page.clock.runFor(1)
  await page.keyboard.press('Escape')
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  }
  assert.deepEqual(errors, [])
  console.log('Pinned toolbar: page-action drag, duplicate, cancel, persistence, original actions, disabled state, keyboard, two-second press and reduced motion passed')
} finally {
  await browser.close()
  await server.close()
}
