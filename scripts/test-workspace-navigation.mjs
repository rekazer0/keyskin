import assert from "node:assert/strict"
import { mkdirSync } from "node:fs"
import { chromium } from "playwright"
import { createServer } from "vite"
import { bdsFixture } from "../tests/helpers/baidu-fixture.mjs"
import { ssfFixture } from "../tests/helpers/ssf-fixture.mjs"

const server = await createServer({ logLevel: "error", server: { host: "127.0.0.1", port: 41907, strictPort: false, hmr: false } })
await server.listen()
const browser = await chromium.launch()
mkdirSync(".ui-current", { recursive: true })
try {
  for (const colorScheme of ["light", "dark"]) {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, colorScheme })
    const errors = []
    page.on("pageerror", error => errors.push(error.message))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
    const nav = page.locator("#workspace-navigation")
    const entry = name => nav.getByRole("button", { name, exact: true })
    assert.deepEqual(await nav.locator("[data-workspace-page]").evaluateAll(nodes => nodes.map(node => node.ariaLabel)), ["文件", "概览", "资源", "工具", "动画", "源代码", "AI 设计"])
    assert.deepEqual(await nav.locator("button > span:last-child").allTextContents(), ["文件", "概览", "资源", "工具", "动画", "源代码", "AI 设计", "分享", "设置"])
    assert.equal(await entry("资源").isDisabled(), true)
    assert.equal(await entry("动画").isDisabled(), true)
    assert.equal(await entry("AI 设计").isDisabled(), true)
    assert.equal(await entry("分享").isDisabled(), true)
    await page.locator("#browser-open").setInputFiles({ name: "导航.bds", mimeType: "application/octet-stream", buffer: Buffer.from(bdsFixture()) })
    await page.waitForFunction(() => !document.querySelector("#open").disabled && !document.querySelector("#file-operation-dialog").open)
    await page.getByRole("button", { name: "编辑模式", exact: true }).click()
    await entry("文件").click()
    assert.equal(await page.locator("#file-project-chooser").isVisible(), true)
    for (const name of ["概览", "资源", "工具", "动画", "源代码", "AI 设计", "分享"]) {
      assert.equal(await entry(name).isEnabled(), true, `${name} remains available with an open skin on the files page`)
    }
    await entry("工具").click()
    await page.locator("#workspace-tools-dialog").waitFor()
    await page.keyboard.press("Escape")
    await page.locator("#workspace-tools-dialog").waitFor({ state: "hidden" })
    assert.equal(await entry("文件").getAttribute("aria-current"), "page")
    await entry("概览").click()
    const initialChanges = await page.evaluate(async () => [...(await import("/src/app/state.ts")).appState.archive.changed])
    const overviewToggle = page.locator("#inspector-source-toggle")
    const sourceEditor = page.locator("#source-editor")
    await overviewToggle.press("Enter")
    await sourceEditor.getByRole("textbox").waitFor()
    assert.equal(await overviewToggle.getAttribute("aria-pressed"), "true")
    assert.equal(await overviewToggle.getAttribute("aria-label"), "返回属性")
    assert.equal(await entry("概览").getAttribute("aria-current"), "page")
    assert.equal(await page.locator(".sidebar-overview").isVisible(), true)
    await overviewToggle.press("Space")
    assert.equal(await overviewToggle.getAttribute("aria-pressed"), "false")
    assert.equal(await sourceEditor.isVisible(), false)
    assert.equal(await page.locator("#quick-inspector").isVisible(), true)
    await page.keyboard.press("Escape")
    await entry("概览").focus()
    await page.keyboard.press("ArrowDown")
    assert.equal(await entry("资源").evaluate(node => node === document.activeElement), true)
    await page.keyboard.press("End")
    assert.equal(await entry("设置").evaluate(node => node === document.activeElement), true)
    for (const [name, target] of [["源代码", "#source-editor"], ["资源", "#resource-list-view"], ["动画", ".animation-library"], ["分享", "#share-dialog"]]) {
      await entry("文件").click()
      await entry(name).click()
      await page.locator(target).waitFor()
      if (name === "分享") {
        await page.keyboard.press("Escape")
        await page.locator(target).waitFor({ state: "hidden" })
        assert.equal(await entry("文件").getAttribute("aria-current"), "page")
      }
      await entry("AI 设计").focus()
      await page.keyboard.press("Enter")
      await page.locator("#ai-design-panel").waitFor({ state: "visible" })
      assert.equal(await entry("AI 设计").getAttribute("aria-current"), "page")
      assert.equal(await nav.locator('[aria-current="page"]').count(), 1)
      assert.equal(await page.locator("#source-editor").isVisible(), false)
      assert.equal(await page.locator("#share-dialog").isVisible(), false)
      assert.equal(await entry("AI 设计").evaluate(node => node === document.activeElement), true)
    }
    await entry("概览").click()
    await page.getByRole("button", { name: "交互预览", exact: true }).click()
    await entry("AI 设计").click()
    await page.locator("#ai-design-panel").waitFor({ state: "visible" })
    assert.equal(await page.locator("#mode").inputValue(), "preview")
    assert.equal(await entry("AI 设计").getAttribute("aria-current"), "page")
    await page.screenshot({ path: `.ui-current/workspace-ai-${colorScheme}.png` })
    await page.getByRole("button", { name: "编辑模式", exact: true }).click()
    await entry("资源").click()
    await page.waitForFunction(() => document.querySelector('[data-workspace-page="resources"]').getAttribute("aria-current") === "page")
    assert.equal(await page.evaluate(async () => (await import("/src/app/state.ts")).appState.resourceConfigActive), true)
    await page.locator("#resource-list-view").waitFor({ state: "visible" })
    await entry("文件").click()
    assert.equal(await entry("文件").getAttribute("aria-current"), "page")
    assert.equal(await page.locator("#file-project-chooser").isVisible(), true, "the resource workspace must not cover the files page")
    assert.equal(await page.locator("#resource-list-view").isVisible(), false)
    await entry("概览").click()
    assert.equal(await page.locator(".sidebar-overview").isVisible(), true)
    await entry("工具").click()
    assert.equal(await page.locator("#workspace-tools-dialog").isVisible(), true)
    assert.equal(await entry("工具").getAttribute("aria-expanded"), "true")
    await page.locator('[data-workspace-tool="panel-scale"]').click()
    await page.locator("#panel-scale-dialog").waitFor({ state: "visible" })
    await page.keyboard.press("Escape")
    await page.locator("#panel-scale-dialog").waitFor({ state: "hidden" })
    await entry("源代码").click()
    assert.equal(await page.locator(".raw-files").isVisible(), true)
    assert.equal(await page.locator("#source-editor").isVisible(), true, JSON.stringify(await page.evaluate(async () => ({ tab: (await import("/src/app/state.ts")).appState.inspectorTab, hidden: document.querySelector("#source-editor").hidden, button: document.querySelector('[data-inspector-tab="source"]').outerHTML, body: document.body.className }))))
    await entry("概览").click()
    await entry("动画").click()
    await page.waitForFunction(() => document.querySelector('[data-workspace-page="animation"]').getAttribute("aria-current") === "page")
    assert.equal(await page.locator(".animation-library").isVisible(), true)
    await entry("概览").click()
    assert.equal(await page.locator(".sidebar-overview").isVisible(), true)
    await entry("分享").click()
    await page.locator("#share-dialog").waitFor({ state: "visible" })
    assert.equal(await entry("分享").getAttribute("aria-expanded"), "true")
    assert.equal(await page.locator("#share-dialog:modal").count(), 1)
    await page.keyboard.press("Escape")
    await page.locator("#share-dialog").waitFor({ state: "hidden" })
    const settings = page.locator("#settings-workspace")
    await entry("设置").click()
    await settings.waitFor()
    assert.equal(await settings.locator(".settings-header button:visible").count(), 0)
    assert.equal(await page.locator("dialog:modal").count(), 0)
    assert.equal(await page.locator("main > .workspace").isVisible(), false)
    assert.equal(await entry("设置").getAttribute("aria-current"), "page")
    assert.equal(await nav.locator('[aria-current="page"]').count(), 1)
    const viewport = page.viewportSize()
    await page.setViewportSize({ width: 1024, height: 620 })
    const geometryAtSmallSize = await settings.evaluate(node => {
      const content = node.querySelector(".settings-content")
      return {
        canScroll: content.scrollHeight > content.clientHeight,
        footerOnScreen: node.querySelector(".settings-footer").getBoundingClientRect().bottom <= innerHeight,
        horizontalOverflow: document.body.scrollWidth > innerWidth,
      }
    })
    assert.deepEqual(geometryAtSmallSize, { canScroll: true, footerOnScreen: true, horizontalOverflow: false })
    await page.setViewportSize(viewport)
    await settings.locator('[data-setting-choice="interface-density"][data-value="compact"]').click()
    await entry("文件").click()
    const discard = page.getByRole("dialog", { name: "放弃未保存的设置？" })
    await discard.getByRole("button", { name: "继续编辑" }).click()
    await discard.waitFor({ state: "hidden" })
    assert.equal(await settings.isVisible(), true)
    assert.equal(await settings.locator("#interface-density").inputValue(), "compact")
    await entry("文件").click()
    await discard.getByRole("button", { name: "放弃更改" }).click()
    await settings.waitFor({ state: "hidden" })
    assert.equal(await settings.locator("#interface-density").inputValue(), "standard")
    await page.waitForFunction(() => document.querySelector('[data-workspace-page="files"]').ariaCurrent === "page")
    await entry("设置").click()
    await settings.waitFor()
    await entry("概览").click()
    await settings.waitFor({ state: "hidden" })
    await page.waitForFunction(() => document.querySelector('[data-workspace-page="overview"]').ariaCurrent === "page")
    assert.equal(await page.locator("main > .workspace").isVisible(), true)
    const geometry = await nav.evaluate(node => {
      const main = document.querySelector("main").getBoundingClientRect()
      const rail = node.getBoundingClientRect()
      const actions = node.querySelector(".ui-workspace-navigation-actions").getBoundingClientRect()
      return { width: rail.width, left: main.left, bottom: actions.bottom, height: innerHeight, overflow: document.body.scrollWidth > innerWidth }
    })
    assert.equal(geometry.width, 80)
    assert.equal(geometry.left, geometry.width)
    assert.ok(geometry.bottom <= geometry.height && !geometry.overflow, JSON.stringify(geometry))
    await page.screenshot({ path: `.ui-current/workspace-navigation-${colorScheme}.png` })
    assert.deepEqual(await page.evaluate(async () => [...(await import("/src/app/state.ts")).appState.archive.changed]), initialChanges, "navigation does not change skin files")
    for (const viewport of [{ width: 390, height: 844 }, { width: 844, height: 390 }]) {
      await page.setViewportSize(viewport)
      assert.equal(await nav.isVisible(), false)
      if (viewport.width === 390) await page.locator("#mobile-navigation").waitFor({ state: "visible" })
      assert.equal(await page.locator(".titlebar").evaluate(node => node.getBoundingClientRect().left), 0)

    }
    await page.setViewportSize({ width: 1440, height: 900 })
    assert.equal(await nav.isVisible(), true)
    await page.locator("#browser-open").setInputFiles({ name: "导航.ssf", mimeType: "application/octet-stream", buffer: Buffer.from(ssfFixture()) })
    await page.getByRole("button", { name: "不导出", exact: true }).click()
    await page.waitForFunction(() => !document.querySelector("#open").disabled && (!document.querySelector("#file-operation-dialog").open || !document.querySelector("#file-operation-close").disabled))
    const close = page.locator("#file-operation-dialog[open] #file-operation-close")
    if (await close.isVisible()) await close.click()
    assert.equal(await entry("动画").isDisabled(), true, "unsupported animation is disabled")
    if (colorScheme === "light") {
      const group = nav.locator(".ui-workspace-navigation-pages")
      const order = () => group.locator("button").evaluateAll(nodes => nodes.map(node => node.dataset.workspacePage))
      const original = await order()
      const current = await nav.locator('[aria-current="page"]').getAttribute("data-workspace-page")
      const start = await entry("文件").boundingBox()
      const end = await entry("AI 设计").boundingBox()
      const x = start.x + start.width / 2
      const y = end.y + end.height / 2 + 2
      async function dragFile() {
        await page.mouse.move(x, start.y + start.height / 2)
        await page.mouse.down()
        await page.mouse.move(x, y)
        await group.locator('[data-insert="after"]').waitFor()
        const dragged = await entry("文件").boundingBox()
        assert.ok(Math.abs(dragged.y + dragged.height / 2 - y) <= 2, "the dragged entry follows the mouse")
        assert.deepEqual(await order(), original, "preview does not change the order")
      }
      await page.mouse.move(x, start.y + start.height / 2)
      await page.mouse.down()
      await page.mouse.move(x, start.y + start.height / 2 + 2)
      await page.mouse.up()
      assert.deepEqual(await order(), original)
      assert.equal(await entry("文件").getAttribute("aria-current"), "page", "small mouse movement still counts as a click")
      await entry("概览").click()
      await dragFile()
      await page.keyboard.press("Escape")
      await page.mouse.up()
      assert.deepEqual(await order(), original)
      await dragFile()
      await page.mouse.move(start.x + 100, y)
      await page.mouse.up()
      assert.deepEqual(await order(), original)
      await dragFile()
      await page.mouse.up()
      assert.deepEqual(await order(), [...original.slice(1), "files"])
      assert.equal(await nav.locator('[aria-current="page"]').getAttribute("data-workspace-page"), current, "drag does not navigate")
      await entry("文件").press("Alt+ArrowUp")
      const reordered = [...original.slice(1, -1), "files", "ai"]
      assert.deepEqual(await order(), reordered)
      assert.equal(await entry("文件").evaluate(node => node === document.activeElement), true)
      await page.keyboard.press("ArrowDown")
      assert.equal(await entry("AI 设计").evaluate(node => node === document.activeElement), true)
      await page.reload()
      assert.deepEqual(await order(), reordered)
    }
    assert.deepEqual(errors, [])
    await page.close()
    console.log(`workspace navigation ${colorScheme}: passed`)
  }
  const touchPage = await browser.newPage({ viewport: { width: 1000, height: 560 }, hasTouch: true })
  await touchPage.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  const group = touchPage.locator(".ui-workspace-navigation-pages")
  const file = group.getByRole("button", { name: "文件", exact: true })
  await group.locator('[data-workspace-page="files"][aria-keyshortcuts]').waitFor()
  const start = await file.boundingBox()
  const bounds = await group.boundingBox()
  const session = await touchPage.context().newCDPSession(touchPage)
  const touch = (type, y) => session.send("Input.dispatchTouchEvent", {
    type, touchPoints: y === undefined ? [] : [{ x: start.x + start.width / 2, y }],
  })
  const y = start.y + start.height / 2
  const scrolled = () => group.evaluate(node => node.scrollTop)
  await touchPage.mouse.move(start.x + start.width / 2, y)
  await touchPage.mouse.down()
  await touchPage.mouse.move(start.x + start.width / 2, bounds.y + bounds.height - 3)
  await group.locator('[data-workspace-page="ai"][data-insert="after"]').waitFor()
  await touchPage.mouse.up()
  const bottomScroll = await scrolled()
  assert.ok(bottomScroll > 0, "holding near the edge scrolls to offscreen entries")
  assert.equal(await group.locator("button").last().getAttribute("data-workspace-page"), "files")
  const last = await file.boundingBox()
  const lastY = Math.min(last.y + last.height / 2, bounds.y + bounds.height - 4)
  await touch("touchStart", lastY)
  await touch("touchMove", lastY + 24)
  await touch("touchMove", lastY + 80)
  await touch("touchEnd")
  await touchPage.waitForFunction(scroll => document.querySelector(".ui-workspace-navigation-pages").scrollTop < scroll, bottomScroll)
  assert.equal(await group.locator("[data-reordering]").count(), 0)
  assert.equal(await group.locator("button").last().getAttribute("data-workspace-page"), "files", "touch swipes only scroll")
  await touchPage.close()
  console.log("workspace navigation compact mouse drag and touch scrolling: passed")
} finally {
  await browser.close()
  await server.close()
}
