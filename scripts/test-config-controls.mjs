import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { SkinArchive } from '../src/skin.ts'

const root = new URL('..', import.meta.url).pathname
const archive = SkinArchive.open(new Uint8Array(readFileSync(`${root}/public/templates/xiaomi-unified-rounded-blur.bds`)))
archive.setText('Info.txt', 'Name=控件测试\nVersionCode=3\nMinImeCode=3\nSupportPlatform=IA\nSupportDarkMode=1\nSkinType=0\nSkinFlags=1\nAbilities=Sound,Custom\nSupportPatch=Accessory|Sound\n')
archive.setText('light/skin/port/controls.pop', '[PANEL]\nSIZE=1080,600\nNO_BLUR=1\n[LIST1]\nLIST_ORDER=1\nLIST_LEVEL=0\nTYPE=2\nSCROLL_SIDE=0\n[ICON1]\nANCHOR_TYPE=5\nPERSIST=3\n[BAR]\nTYPE=0\nANCHOR_TYPE=1\n[STYLE1]\nFONT_CLEARTYPE=1\nNM_COLOR=80123456\n[EXTRA]\nTYPE=custom\nSIZE=1/3,2/3\n')
const server = await createServer({ root, logLevel: 'error', server: { host: '127.0.0.1', port: 41936, strictPort: false } })
await server.listen()
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const selectFile = path => page.evaluate(async path => { await (await import('/src/app/navigation.ts')).selectFile(path) }, path)
const value = (section, key) => page.evaluate(async ({section, key}) => (await import('/src/app/state.ts')).appState.selectedDocument.get(section, key), { section, key })
const history = () => page.evaluate(async () => (await import('/src/app/state.ts')).appState.undoStack.length)
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  await page.locator('#browser-open').setInputFiles({ name: 'controls.bds', mimeType: 'application/octet-stream', buffer: Buffer.from(archive.toBytes('bds')) })
  await page.waitForFunction(() => !document.querySelector('#open').disabled)
  const close = page.locator('#file-operation-dialog[open] #file-operation-close')
  if (await close.isVisible()) await close.click()
  await page.getByRole('button', { name: '编辑模式', exact: true }).click()
  await selectFile('Info.txt')
  const skinRow = key => page.locator(`[data-skin-field="${key}"]`).locator('xpath=ancestor::label[1]')
  assert.equal(await skinRow('SupportDarkMode').getByRole('switch').isChecked(), true)
  assert.equal(await skinRow('SkinType').getByRole('switch').isChecked(), true, '0 means theme loading enabled')
  assert.equal(await skinRow('MinImeCode').locator('select').inputValue(), '3')
  assert.equal(await skinRow('Abilities').getByRole('button', { name: 'Custom（扩展）', exact: true }).getAttribute('aria-pressed'), 'true')
  await skinRow('SupportPatch').getByRole('button', { name: '动效', exact: true }).click()
  assert.equal(await value('', 'SupportPatch'), 'Accessory|Sound|Anim')
  await skinRow('SupportPlatform').getByRole('button', { name: 'iOS', exact: true }).click()
  assert.equal(await value('', 'SupportPlatform'), 'A')
  const before = await history()
  await skinRow('Abilities').getByRole('button', { name: '动效', exact: true }).click()
  assert.equal(await value('', 'Abilities'), 'Sound,Custom,Animation')
  assert.equal(await history(), before + 1)
  await page.locator('.inspector-reset').click()
  assert.equal(await value('', 'Abilities'), 'Sound,Custom')
  assert.equal(await skinRow('Abilities').getByRole('button', { name: '动效', exact: true }).getAttribute('aria-pressed'), 'false')
  assert.equal(await value('', 'SupportPatch'), 'Accessory|Sound')
  assert.equal(await value('', 'SupportPlatform'), 'IA')
  await skinRow('SkinType').getByRole('switch').uncheck()
  assert.equal(await value('', 'SkinType'), '1')
  await page.evaluate(async () => (await import('/src/app/edit-history.ts')).undo())
  assert.equal(await value('', 'SkinType'), '0')
  assert.equal(await skinRow('SkinType').getByRole('switch').isChecked(), true)
  await selectFile('light/skin/port/controls.pop')
  const row = key => page.locator(`#document-fields [data-document-key="${key}"]`).first()
  assert.equal(await row('NO_BLUR').getByRole('switch').isChecked(), true)
  assert.equal(await row('LIST_ORDER').getByRole('button', { name: '横排', exact: true }).getAttribute('aria-pressed'), 'true')
  await row('LIST_ORDER').getByRole('button', { name: '竖排', exact: true }).click()
  assert.equal(await value('LIST1', 'LIST_ORDER'), '0')
  await row('PERSIST').getByRole('button', { name: '有候选', exact: true }).click()
  assert.equal(await value('ICON1', 'PERSIST'), '2')
  assert.equal(await row('ANCHOR_TYPE').locator('.ui-segmented').count(), 0, '锚点不使用九宫格')
  assert.equal(await row('ANCHOR_TYPE').getByRole('textbox').inputValue(), '5')
  const anchorHistory = await history()
  await row('ANCHOR_TYPE').getByRole('textbox').fill('3')
  await row('ANCHOR_TYPE').getByRole('textbox').press('Tab')
  assert.equal(await value('ICON1', 'ANCHOR_TYPE'), '3')
  assert.equal(await history(), anchorHistory + 1)
  assert.equal(await row('TYPE').getByRole('button', { name: '面板上方', exact: true }).getAttribute('aria-pressed'), 'true', 'LIST TYPE=2 拆成 位置 × 时机')
  await row('TYPE').getByRole('button', { name: '有列表项时', exact: true }).click()
  assert.equal(await value('LIST1', 'TYPE'), '3')
  assert.equal(await row('FONT_CLEARTYPE').getByRole('switch').isChecked(), true)
  const color = row('NM_COLOR')
  await color.locator('.ui-swatch').click()
  await color.locator('input[type=color]').fill('#abcdef')
  await color.locator('input[type=color]').dispatchEvent('change')
  assert.equal(await value('STYLE1', 'NM_COLOR'), '80ABCDEF', 'picker preserves the exact original alpha byte')
  await color.locator('input[type=number]').fill('0')
  await color.locator('input[type=number]').press('Tab')
  assert.equal(await value('STYLE1', 'NM_COLOR'), '00ABCDEF', 'zero alpha remains transparent')
  // 能力表会给每个分区各补一行尺寸：这里只看布局自己的 [EXTRA] 分区。
  assert.equal(await page.locator('#document-fields > section').filter({ hasText: /^EXTRA/ }).locator('[data-document-key=SIZE] input').inputValue(), '1/3,2/3')
  await page.locator('.inspector-reset').click()
  assert.equal(await value('LIST1', 'LIST_ORDER'), '1')
  assert.equal(await value('ICON1', 'PERSIST'), '3')
  assert.equal(await value('ICON1', 'ANCHOR_TYPE'), '5')
  assert.equal(await row('ANCHOR_TYPE').getByRole('textbox').inputValue(), '5')
  assert.equal(await value('LIST1', 'TYPE'), '2')
  assert.equal(await value('STYLE1', 'NM_COLOR'), '80123456')
  await row('ANCHOR_TYPE').getByRole('textbox').fill('9')
  await row('ANCHOR_TYPE').getByRole('textbox').press('Tab')
  assert.equal(await value('ICON1', 'ANCHOR_TYPE'), '9')
  await page.evaluate(async () => (await import('/src/app/edit-history.ts')).undo())
  assert.equal(await value('ICON1', 'ANCHOR_TYPE'), '5')
  assert.equal(await row('ANCHOR_TYPE').getByRole('textbox').inputValue(), '5')
  await page.getByRole('button', { name: '交互预览', exact: true }).click()
  assert.equal(await row('NO_BLUR').getByRole('switch').isDisabled(), true)
  assert.equal(await row('ANCHOR_TYPE').getByRole('textbox').isDisabled(), true)
  await selectFile('Info.txt')
  assert.equal(await skinRow('SkinType').getByRole('switch').isDisabled(), true)
  assert.equal(await skinRow('Abilities').getByRole('button', { name: '动效', exact: true }).isDisabled(), true)
  await page.evaluate(async () => {
    const { configValueControl } = await import('/src/app/config-value-control.ts')
    const input = document.createElement('input')
    input.value = 'future-value'
    const control = configValueControl(input, 'ICON1', 'PERSIST', '显示时机')
    if (input.value !== 'future-value' || control.querySelector('select').value !== 'future-value') throw new Error('unknown enum lost')
    const { fieldControl } = await import('/src/app/property-rows.ts')
    const mixed = fieldControl({ kind: 'choice', value: '1', options: [['0', '竖排'], ['1', '横排']] }, '文字方向', () => {}, { editable: true, mixed: true })
    const select = mixed.querySelector('select')
    if (!select || select.value !== '' || select.selectedOptions[0].textContent !== '混合') throw new Error('mixed choice shows a stale selection')
  })
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.evaluate(() => { for (const field of document.querySelectorAll('[data-config-control]')) { if (field.scrollWidth > field.clientWidth + 2) throw new Error('config control overflow') } })
  }
  assert.deepEqual(errors, [])
  console.log('Typed Baidu config controls: metadata, enums, extension preservation, writeback, undo/reset, zero alpha and read-only checks passed')
} catch (error) {
  console.error('Config control state:', await page.evaluate(async () => ({ path: (await import('/src/app/state.ts')).appState.selectedPath })))
  throw error
} finally {
  await browser.close()
  await server.close()
}
