import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { strFromU8, strToU8, unzipSync, zipSync } from 'fflate'
import { ssfFixture } from '../tests/helpers/ssf-fixture.mjs'

const keys = '1080/status1/keys.ini', anim = '1080/status1/anim.ini', sounds = 'default/sound_android.ini'
const files = unzipSync(ssfFixture())
files[keys] = strToU8(strFromU8(files[keys]) + '\n[Key_W]\nANIM_STYLE=Anim_Style_Other\n')
files[anim] = strToU8('[Anim_Style_Key_Qwertys]\nBG_ANIM=Animation_scale\nFG_ANIM=Animation_scale\nDECO_ANIM=Animation_deco\nDECO_ANIM_NUMBER=-1\nSET_PRESSED=0\n[Anim_Style_Other]\nBG_ANIM=Animation_scale\n[Animation_scale]\nDOWN_ANIM_OBJ=Object_scale\n[Object_scale]\nANIM=Scale\n[Scale]\nTYPE=2\nDURATION=800\nKEYFRAME=Track,Track\n[Track]\nTIME=0,0.5,1\nVALUE=1,0.5,1\n')
files[anim] = strToU8(strFromU8(files[anim]) + '[Animation_deco]\nDOWN_ANIM_OBJ=Object_deco\n[Object_deco]\nIMG=26key.png\nRATE_KEY_W=0.5\nRATE_KEY_H=0.5\nPOS_ANCHOR=0\nANIM=Fly\n[Fly]\nTYPE=1\nDURATION=800\nVELOCITY=0,-500\nACCELERATION=0,0\n')
files[sounds] = strToU8(strFromU8(files[sounds]) + '\n[Key_Q]\nsound=s_code\n[Key_W]\nsound=s_del\n')
const server = await createServer({ root: new URL('..', import.meta.url).pathname, logLevel: 'error', server: { host: '127.0.0.1', port: 41966, strictPort: false, hmr: false } })
await server.listen()
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const fields = page.locator('#document-fields')
const row = key => fields.locator(`[data-document-key="${key}"]`)
const read = (path, section, key) => page.evaluate(async ({ path, section, key }) => (await import('/src/app/ssf-documents.ts')).ssfDocument(path).get(section, key), { path, section, key })
const undo = () => page.evaluate(async () => (await import('/src/app/edit-history.ts')).undo())
const edit = async (input, value) => { await input.fill(value); await input.press('Enter') }
const selectKeys = actions => page.evaluate(async actions => {
  const { selectFile } = await import('/src/app/navigation.ts')
  const { appState } = await import('/src/app/state.ts')
  const { preview } = await import('/src/app/canvas-interaction.ts')
  const { populateKeyInspector } = await import('/src/app/key-inspector.ts')
  selectFile('light/skin/port/py_26.ini')
  await preview.whenDrawn()
  appState.selectedKeySections = actions.map(action => preview.keys.find(key => key.center === action).section)
  populateKeyInspector()
}, actions)
const picker = () => page.frameLocator('#picker-frame')
const dialog = () => page.locator('#picker-dialog')
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  await page.locator('#browser-open').setInputFiles({ name: 'media.ssf', mimeType: 'application/octet-stream', buffer: Buffer.from(zipSync(files)) })
  await page.waitForFunction(() => !document.querySelector('#open').disabled)
  const close = page.locator('#file-operation-dialog[open] #file-operation-close')
  if (await close.isVisible()) await close.click()
  await selectKeys(['q'])
  assert.equal(await row('ANIM_STYLE').locator('.ui-style-ref-name').isDisabled(), true)
  assert.equal(await row('BG_ANIM').count(), 0)
  await page.getByRole('button', { name: '编辑模式', exact: true }).click()
  await row('ANIM_STYLE').scrollIntoViewIfNeeded()
  await row('ANIM_STYLE').locator('.ui-animation-player canvas').waitFor()
  await page.waitForFunction(() => document.querySelector('[data-document-key="ANIM_STYLE"] .ui-animation-player')?.dataset.playing === 'true')
  const frames = await row('ANIM_STYLE').locator('canvas').evaluate(async canvas => {
    const pixels = () => [...canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data].reduce((sum, value) => sum + value, 0)
    const before = pixels()
    await new Promise(resolve => setTimeout(resolve, 180))
    return [before, pixels()]
  })
  assert.notEqual(frames[0], frames[1], 'real SSF animation changes the thumbnail')
  await row('ANIM_STYLE').locator('.ui-style-state').click()
  await picker().locator('#style-library-grid [data-style-id="Anim_Style_Key_Qwertys"][aria-selected="true"]').waitFor()
  assert.deepEqual(await picker().locator('[role=option]').evaluateAll(cards => cards.map(card => card.dataset.styleId)), ['Anim_Style_Key_Qwertys', 'Anim_Style_Other'])
  assert.equal(await picker().locator('[data-library-kind="anim"]').getAttribute('aria-pressed'), 'true')
  assert.equal(await picker().locator('[data-library-mode="images"]').isDisabled(), true)
  await picker().locator('#style-library-preview .ui-animation-player[data-playing="true"]').waitFor()
  const pickerFrames = await picker().locator('#style-library-preview canvas').evaluate(async canvas => {
    const pixels = () => [...canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data].reduce((sum, value) => sum + value, 0)
    const before = pixels()
    await new Promise(resolve => setTimeout(resolve, 180))
    return [before, pixels()]
  })
  assert.notEqual(pickerFrames[0], pickerFrames[1], 'shared picker plays native SSF motion')
  await page.screenshot({ path: '/tmp/bdi-ssf-shared-animation-picker.png' })
  await picker().locator('#resource-search').fill('Other')
  assert.equal(await picker().locator('#style-library-grid [role=option]').count(), 1)
  await picker().locator('#resource-search').press('Escape')
  assert.equal(await picker().locator('#resource-search').inputValue(), '')
  await picker().locator('#style-library-grid [data-style-id="Anim_Style_Other"]').click()
  await picker().locator('#picker-close').click()
  await dialog().waitFor({ state: 'hidden' })
  await row('ANIM_STYLE').locator('.ui-style-state').click()
  await picker().locator('#style-library-grid [data-style-id="Anim_Style_Key_Qwertys"][aria-selected="true"]').waitFor()

  await picker().locator('[data-style-id="Anim_Style_Other"]').click()
  assert.equal(await read(keys, 'Key_Q', 'ANIM_STYLE'), 'Anim_Style_Key_Qwertys', 'selection alone does not write')
  await picker().locator('[data-style-id="Anim_Style_Other"]').press('Escape')
  assert.equal(await picker().locator('#style-library-preview').isVisible(), false)
  await picker().locator('[data-style-id="Anim_Style_Other"]').press('Escape')
  await dialog().waitFor({ state: 'hidden' })
  await row('ANIM_STYLE').locator('.ui-style-remove').click()
  assert.equal(await read(keys, 'Key_Q', 'ANIM_STYLE'), undefined)
  await row('ANIM_STYLE').getByRole('button', { name: '添加动画样式' }).click()
  await picker().locator('[data-style-id="Anim_Style_Other"]').focus()
  await picker().locator('[data-style-id="Anim_Style_Other"]').press('End')
  await picker().locator('[data-style-id="Anim_Style_Other"]').press('Enter')
  await dialog().waitFor({ state: 'hidden' })
  assert.equal(await read(keys, 'Key_Q', 'ANIM_STYLE'), 'Anim_Style_Other')
  await page.locator('.inspector-reset').click()
  assert.equal(await read(keys, 'Key_Q', 'ANIM_STYLE'), 'Anim_Style_Key_Qwertys')
  assert.equal(await row('sound').getByRole('button', { name: '试听', exact: true }).isEnabled(), true)
  await row('sound').locator('.ui-style-state').click()
  const currentSound = picker().locator('#style-library-grid [data-style-id="s_code"]')
  await currentSound.locator('.ui-style-sound').waitFor()
  assert.equal(await picker().locator('#picker-title').textContent(), '全部样式')
  assert.equal(await currentSound.getAttribute('aria-selected'), 'true')
  assert.equal(await picker().locator('[data-library-mode="images"]').isDisabled(), true)
  await page.waitForTimeout(350)
  const geometry = await currentSound.evaluate(card => {
    const preview = card.querySelector('.ui-style-preview').getBoundingClientRect()
    const sample = card.querySelector('.ui-style-sound').getBoundingClientRect()
    return { width: preview.width, sampleWidth: sample.width, height: preview.height }
  })
  assert.ok(Math.abs(geometry.width - geometry.sampleWidth) < 2, 'sound sample uses the full card width')
  assert.ok(geometry.height < 80, 'sound card has no empty image-sized preview')
  await page.evaluate(async () => {
    const { appState } = await import('/src/app/state.ts')
    const start = AudioBufferSourceNode.prototype.start
    AudioBufferSourceNode.prototype.start = function (...args) {
      window.previewedSoundPath = appState.keySoundPath
      return start.apply(this, args)
    }
  })
  await currentSound.getByRole('button', { name: '试听', exact: true }).click()
  await page.waitForFunction(() => window.previewedSoundPath === 'default/s_code.wav')
  assert.equal(await dialog().isVisible(), true, 'audition does not apply the sound or close the picker')
  await picker().locator('#resource-search').fill('s_del')
  assert.equal(await picker().locator('#style-library-grid [role=option]').count(), 1)
  await picker().locator('#resource-search').press('Escape')
  await picker().locator('[data-style-id="s_del"]').click()
  assert.equal(await read(sounds, 'Key_Q', 'sound'), 's_code', 'selection alone does not write a sound')
  await picker().locator('#picker-close').click()
  await dialog().waitFor({ state: 'hidden' })
  await row('sound').locator('.ui-style-state').click()
  await picker().locator('[data-style-id="s_code"][aria-selected="true"]').waitFor()
  await page.screenshot({ path: '/tmp/bdi-ssf-shared-sound-picker.png' })
  await picker().locator('[data-style-id="s_del"]').dblclick()
  await dialog().waitFor({ state: 'hidden' })
  assert.equal(await read(sounds, 'Key_Q', 'sound'), 's_del')
  await row('sound').locator('.ui-style-remove').click()
  assert.equal(await read(sounds, 'Key_Q', 'sound'), undefined)
  assert.equal(await row('sound').getByRole('button', { name: '添加音效' }).count(), 1)
  await undo(); await undo()
  await row('sound').locator('.ui-style-state').click()
  await picker().locator('[data-style-id="s_code"][aria-selected="true"]').waitFor()
  await picker().locator('#style-library-edit').click()
  await dialog().waitFor({ state: 'hidden' })
  await page.locator('.ui-sound-row [data-sound-id="file:default/s_code.wav"][aria-selected="true"]').waitFor()
  assert.equal(await read(sounds, 'Key_Q', 'sound'), 's_code', 'editing a sound opens its resource without replacing the reference')
  await selectKeys(['q'])
  await row('ANIM_STYLE').locator('.ui-style-remove').click()
  await selectKeys(['q', 'w'])
  assert.equal(await row('ANIM_STYLE').locator('.ui-style-ref-name').getAttribute('placeholder'), '混合', 'a missing first reference still exposes the mixed field')
  await undo()
  assert.equal(await row('ANIM_STYLE').locator('.ui-style-ref-name').getAttribute('placeholder'), '混合')
  assert.equal(await row('sound').locator('.ui-style-ref-name').getAttribute('placeholder'), '混合')
  await edit(row('ANIM_STYLE').locator('.ui-style-ref-name'), 'Anim_Style_Other')
  assert.equal(await read(keys, 'Key_Q', 'ANIM_STYLE'), 'Anim_Style_Other')
  assert.equal(await read(keys, 'Key_W', 'ANIM_STYLE'), 'Anim_Style_Other')
  await undo()
  assert.equal(await read(keys, 'Key_Q', 'ANIM_STYLE'), 'Anim_Style_Key_Qwertys')
  assert.equal(await read(keys, 'Key_W', 'ANIM_STYLE'), 'Anim_Style_Other')
  await selectKeys(['q'])
  await edit(row('ANIM_STYLE').locator('.ui-style-ref-name'), 'MissingStyle')
  assert.equal(await row('ANIM_STYLE').locator('.ui-empty').getAttribute('title'), '引用缺失：MissingStyle')
  await undo()
  await row('ANIM_STYLE').locator('.ui-style-state').click()
  await picker().locator('#style-library-grid [data-style-id="Anim_Style_Key_Qwertys"][aria-selected="true"]').waitFor()
  await picker().locator('#style-library-edit').click()
  await dialog().waitFor({ state: 'hidden' })
  await fields.locator('[data-inspector-group-label="动画 Style Key Qwertys"]').waitFor()
  assert.equal(await read(keys, 'Key_Q', 'ANIM_STYLE'), 'Anim_Style_Key_Qwertys', 'editing from the shared preview does not replace the reference')
  await selectKeys(['q'])
  await row('ANIM_STYLE').locator('.ui-style-state').click({ modifiers: [process.platform === 'darwin' ? 'Meta' : 'Control'] })
  const style = fields.locator('[data-inspector-group-label="动画 Style Key Qwertys"]')
  for (const key of ['BG_ANIM', 'FG_ANIM', 'DECO_ANIM']) assert.equal(await style.locator(`[data-document-key="${key}"] .ui-style-ref`).count(), 1)
  for (const key of ['BG_ANIM', 'FG_ANIM', 'DECO_ANIM']) {
    const field = style.locator(`[data-document-key="${key}"]`)
    const original = await read(anim, 'Anim_Style_Key_Qwertys', key)
    const replacement = original === 'Animation_scale' ? 'Animation_deco' : 'Animation_scale'
    await field.locator('.ui-style-state').click()
    await picker().locator(`#style-library-grid [data-style-id="${original}"][aria-selected="true"]`).waitFor()
    assert.deepEqual(await picker().locator('#style-library-grid [role=option]').evaluateAll(cards => cards.map(card => card.dataset.styleId)), ['Animation_scale', 'Animation_deco'])
    await picker().locator('#style-library-preview .ui-animation-player[data-playing="true"]').waitFor()
    await picker().locator(`#style-library-grid [data-style-id="${replacement}"]`).click()
    assert.equal(await read(anim, 'Anim_Style_Key_Qwertys', key), original)
    await picker().locator('#style-library-apply').click()
    await dialog().waitFor({ state: 'hidden' })
    assert.equal(await read(anim, 'Anim_Style_Key_Qwertys', key), replacement)
    await undo()
    assert.equal(await read(anim, 'Anim_Style_Key_Qwertys', key), original)
  }
  await style.locator('[data-document-key="SET_PRESSED"] input').check()
  assert.equal(await read(anim, 'Anim_Style_Key_Qwertys', 'SET_PRESSED'), '1')
  await undo()
  assert.equal(await read(anim, 'Anim_Style_Key_Qwertys', 'SET_PRESSED'), '0')
  await edit(style.locator('[data-document-key="DECO_ANIM_NUMBER"] input'), '2')
  assert.equal(await read(anim, 'Anim_Style_Key_Qwertys', 'DECO_ANIM_NUMBER'), '2')
  await undo()
  assert.equal(await read(anim, 'Anim_Style_Key_Qwertys', 'DECO_ANIM_NUMBER'), '-1')
  assert.deepEqual(errors, [])
  await selectKeys(['q'])
  await row('ANIM_STYLE').scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/bdi-ssf-media-fields.png' })
  console.log('SSF media cards: real animation, picker, keyboard, sound, removal, reset, undo, mixed values and missing references passed')
} catch (error) {
  await page.screenshot({ path: '/tmp/bdi-ssf-media-fields-failure.png' })
  throw error
} finally {
  await browser.close()
  await server.close()
}
